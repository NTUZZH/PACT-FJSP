COMBOS = list(M.COMBOS)
SEEDS = [301, 302, 303, 304, 305]


def cell(mean, half):
    """One cell as p100 stores it: mean, interval, verdicts at both margins, direction."""
    lo, hi = mean - half, mean + half
    return {'mean': mean, 'lo': lo, 'hi': hi, 't_lo': lo - 0.1, 't_hi': hi + 0.1,
            'seed_means': [mean] * len(SEEDS), 'scheme': 'hierarchical',
            'stream': 'default_rng(11)', 'k': len(SEEDS), 'n': 100, 'c': 1,
            'direction': SF.direction(lo, hi), 'v0.5': SF.verdict(lo, hi, 0.5),
            'v1.0': SF.verdict(lo, hi, 1.0)}


def synthetic_cells():
    """The diagonal near zero, the specialist of all three rules above zero on four columns,
    the others spread, with several near-equal means in one column so that they would
    overlap without the sideways spread."""
    rng = np.random.default_rng(5)
    out = {}
    for i, r in enumerate(COMBOS):
        for j, c in enumerate(COMBOS):
            if r == c:
                out[(r, c)] = cell(round(0.1 * (j - 3.5) / 3.5, 4), 0.35)
            elif r == 'LSW':
                out[(r, c)] = cell([5.9, 0.1, 1.4, 4.8, 0.2, -0.05, 1.2][j], 0.6 + 0.1 * j)
            elif c == 'LS':
                out[(r, c)] = cell(0.50 + 0.01 * i, 0.4)       # six means within 0.07
            else:
                out[(r, c)] = cell(round(float(rng.uniform(-0.4, 4.0)), 4), 0.5)
    return out


def write_world(tmp_path, cells=None):
    cells = synthetic_cells() if cells is None else cells
    rec = dict(generator=P100.GENERATOR, environment='exact', boot=2000, alpha=0.05,
               margins=[0.5, 1.0], seeds=SEEDS, n=100,
               cells={f'{r}|{c}': v for (r, c), v in cells.items()},
               sign='d = 100 (specialist - policy) / policy; positive = specialist longer')
    lines = [f'% Generated by {P100.GENERATOR} -- do not hand-edit',
             f'\\newcommand{{\\XevBoot}}{{2000}}\\newcommand{{\\XevSeedN}}{{{len(SEEDS)}}}'
             f'\\newcommand{{\\XevInstN}}{{100}}\\newcommand{{\\XevOffN}}{{56}}']
    for (r, c), v in cells.items():
        lines.append(P100.cell_line(f'Xev{r}On{c}', v, 'synthetic cell'))
    d = tmp_path / 'world'
    (d / 'results').mkdir(parents=True)
    (d / 'manuscript').mkdir(parents=True)
    js = d / 'results' / 'cross_eval.json'
    js.write_text(json.dumps(rec, indent=1))
    mac = d / 'manuscript' / 'macros_crosseval.tex'
    mac.write_text('\n'.join(lines) + '\n')
    return dict(json=str(js), macros=str(mac), cells=cells, rec=rec)


@pytest.fixture
def world(tmp_path):
    return write_world(tmp_path)


def _edit_macro(path, name, new):
    text = open(path).read()
    pat = re.compile(r'(\\newcommand\{\\' + name + r'\})\{[^}]*\}')
    assert len(pat.findall(text)) == 1
    open(path, 'w').write(pat.sub(lambda m: m.group(1) + '{' + new + '}', text))


def _drop_macro(path, name):
    text = open(path).read()
    new = re.sub(r'\\newcommand\{\\' + name + r'\}\{[^}]*\}', '', text)
    assert new != text
    open(path, 'w').write(new)


def _marks(ax):
    """Vertical intervals (x, lo, hi) and markers (marker, face, x, y) the axes draws."""
    iv, mk = [], []
    for ln in ax.lines:
        x, y = list(map(float, ln.get_xdata())), list(map(float, ln.get_ydata()))
        if len(x) == 2 and x[0] == x[1]:
            iv.append((x[0], y[0], y[1]))
        elif len(x) == 1:
            face = 'white' if str(ln.get_markerfacecolor()) == 'white' else 'filled'
            mk.append((ln.get_marker(), face, ln.get_markersize(), x[0], y[0]))
    return iv, mk


# ================================================================== the figure
def test_the_figure_draws_the_record(world, tmp_path, monkeypatch):
    kept = []
    monkeypatch.setattr(M.plt, 'close', kept.append)
    out = tmp_path / 'fig'
    written = M.fq2_reuse(world['json'], world['macros'], str(out))
    assert sorted(os.path.basename(p) for p in written) == ['fq2_reuse.pdf', 'fq2_reuse.png']
    assert all(os.path.isfile(p) and p.startswith(str(out)) for p in written)
    (fig,) = kept
    (ax,) = fig.axes
    iv, mk = _marks(ax)
    C = world['cells']
    col = {c: j for j, c in enumerate(COMBOS)}

    def column(x):
        j = int(round(x))
        assert abs(x - j) < 0.5
        return COMBOS[j]

    # intervals: the specialist of each combination and the specialist of all three rules
    want = sorted([('own', c, C[(c, c)]['lo'], C[(c, c)]['hi']) for c in COMBOS]
                  + [('all', c, C[('LSW', c)]['lo'], C[('LSW', c)]['hi'])
                     for c in COMBOS if c != 'LSW'], key=lambda t: (t[1], t[2]))
    got = sorted((column(x), lo, hi) for x, lo, hi in iv)
    assert got == sorted((c, lo, hi) for _, c, lo, hi in want)
    # markers by kind, each in its own column
    own = sorted((column(x), y) for m, f, s, x, y in mk if m == 'o' and f == 'filled')
    alls = sorted((column(x), y) for m, f, s, x, y in mk if m == 's')
    other = sorted((column(x), y) for m, f, s, x, y in mk if m == 'o' and f == 'white')
    assert own == sorted((c, C[(c, c)]['mean']) for c in COMBOS)
    assert alls == sorted((c, C[('LSW', c)]['mean']) for c in COMBOS if c != 'LSW')
    assert other == sorted((c, C[(r, c)]['mean']) for c in COMBOS for r in COMBOS
                           if r not in (c, 'LSW'))
    per = {c: sum(1 for cc, _ in other if cc == c) for c in COMBOS}
    assert per == {c: (7 if c == 'LSW' else 6) for c in COMBOS}
    # left of the tick the two with intervals, right of it the others
    for m, f, s, x, y in mk:
        side = x - col[column(x)]
        assert (side < 0) == (not (m == 'o' and f == 'white'))
    # the band of the 1% margin, the zero line, no text inside the axes, size and legend
    horizontal = [tuple(ln.get_ydata()) for ln in ax.lines
                  if len(ln.get_xdata()) == 2 and ln.get_xdata()[0] != ln.get_xdata()[1]]
    assert (0, 0) in horizontal
    assert [(p.get_y(), p.get_y() + p.get_height()) for p in ax.patches] == [(-1.0, 1.0)]
    assert not ax.texts
    assert tuple(round(v, 2) for v in fig.get_size_inches()) == (M.FIG_W, 2.70)
    labels = [t.get_text() for t in fig.legends[0].get_texts()]
    assert labels == ['specialist of the combination', 'specialist of all three rules',
                      'other specialists', '\u00b11% margin']
    # the combination names in math italic, the form of the manuscript's text
    assert [t.get_text() for t in ax.get_xticklabels()] == [
        '$N$', '$L$', '$S$', '$W$', '$LS$', '$LW$', '$SW$', '$LSW$']


def test_close_means_of_the_other_specialists_do_not_overlap(world, monkeypatch):
    """Column LS holds six means within 0.07 percentage points; the check of the marks
    runs inside the figure, and here the circles are held apart once more."""
    kept = []
    monkeypatch.setattr(M.plt, 'close', kept.append)
    M.fq2_reuse(world['json'], world['macros'], str(world['json']) + '_fig')
    ax = kept[0].axes[0]
    k = 72.0 / kept[0].dpi
    pts = [ax.transData.transform((x, y)) * k for m, f, s, x, y in _marks(ax)[1]
           if m == 'o' and f == 'white' and int(round(x)) == COMBOS.index('LS')]
    assert len(pts) == 6
    r = M._fq2_radius('other')
    for i in range(len(pts)):
        for j in range(i + 1, len(pts)):
            assert np.hypot(*(pts[i] - pts[j])) >= 2 * r


def test_swarm_places_equal_heights_apart_and_refuses_when_full():
    size = 2 * M._fq2_radius('other')
    xs = M._fq2_swarm([100.0] * 5, -50.0, 50.0, size)
    assert len(set(xs)) == 5
    assert min(abs(a - b) for i, a in enumerate(xs) for b in xs[i + 1:]) >= size + M.FQ2_CLEAR
    with pytest.raises(SystemExit, match='no free place'):
        M._fq2_swarm([100.0] * 5, M.FQ2_SWARM_X0, M.FQ2_SWARM_X0 + 3.0, size)


# ================================================================== the gate
def test_the_gate_matches_every_plotted_value(world):
    X = M.load_crosseval(world['json'])
    rows = M.gate_crosseval(X, world['macros'])
    assert all(r[-1] == 'match' for r in rows)
    # 8 own and 7 all intervals with their means (3 values each), 49 other means, 3 counts
    assert len(rows) == 3 * (8 + 7) + 49 + 3


def test_the_gate_refuses_a_macro_that_disagrees_in_one_number(world):
    hi = world['cells'][('LSW', 'N')]['hi']
    _edit_macro(world['macros'], 'XevLSWOnNHi', P100.f2(hi + 0.02))
    X = M.load_crosseval(world['json'])
    with pytest.raises(SystemExit, match=r'disagrees.*\n.*XevLSWOnNHi'):
        M.gate_crosseval(X, world['macros'])


def test_the_gate_refuses_a_count_of_another_run(world):
    _edit_macro(world['macros'], 'XevSeedN', '3')
    X = M.load_crosseval(world['json'])
    with pytest.raises(SystemExit, match='XevSeedN = 3'):
        M.gate_crosseval(X, world['macros'])
    _drop_macro(world['macros'], 'XevSeedN')
    with pytest.raises(SystemExit, match=r'\\XevSeedN: no macro'):
        M.gate_crosseval(X, world['macros'])


def test_a_cell_without_a_macro_is_compared_with_the_record_only(world, tmp_path):
    _drop_macro(world['macros'], 'XevLWOnN')
    X = M.load_crosseval(world['json'])
    rows = M.gate_crosseval(X, world['macros'])
    lacking = [r for r in rows if r[-1] != 'match']
    assert [(r[1], r[2], r[-1]) for r in lacking] == [('LW under N', 'mean',
                                                       'no macro, record only')]
    with pytest.raises(SystemExit, match='macro file .* not found'):
        M.gate_crosseval(X, str(tmp_path / 'absent.tex'))


# ================================================================== the record
def test_a_missing_or_incomplete_record_is_refused(world, tmp_path):
    with pytest.raises(SystemExit, match='not found'):
        M.load_crosseval(str(tmp_path / 'absent.json'))
    rec = json.load(open(world['json']))
    del rec['cells']['SW|LS']
    del rec['cells']['N|N']['hi']
    open(world['json'], 'w').write(json.dumps(rec))
    with pytest.raises(SystemExit, match=r'incomplete: 2 of 64 cells missing.*N\|N.*SW\|LS'):
        M.load_crosseval(world['json'])


def test_a_verdict_or_direction_that_the_interval_does_not_give_is_refused(world):
    rec = json.load(open(world['json']))
    c = rec['cells']['LSW|N']
    assert c['v1.0'] == 'inferior'
    c['v1.0'] = 'equivalent'
    open(world['json'], 'w').write(json.dumps(rec))
    with pytest.raises(SystemExit, match=r'LSW\|N: verdict'):
        M.load_crosseval(world['json'])
    c['v1.0'] = 'inferior'
    c['direction'] = 'ahead'
    open(world['json'], 'w').write(json.dumps(rec))
    with pytest.raises(SystemExit, match=r'LSW\|N: direction'):
        M.load_crosseval(world['json'])
    c['direction'] = 'behind'
    c['mean'] = c['hi'] + 0.1
    open(world['json'], 'w').write(json.dumps(rec))
    with pytest.raises(SystemExit, match='outside'):
        M.load_crosseval(world['json'])


@pytest.mark.parametrize('key,value,message', [
    ('sign', 'd = 100 (policy - specialist) / specialist', 'states the sign'),
    ('generator', 'scripts/p88_family_inference.py', 'was written by'),
    ('environment', 'legacy', 'environment'),
])
def test_a_record_of_another_sign_or_origin_is_refused(world, key, value, message):
    rec = json.load(open(world['json']))
    rec[key] = value
    open(world['json'], 'w').write(json.dumps(rec))
    with pytest.raises(SystemExit, match=message):
        M.load_crosseval(world['json'])


