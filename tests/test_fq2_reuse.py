"""The figure fq2_reuse of scripts/make_figures.py: each specialist under each rule
combination against the policy, from the record of scripts/p100_cross_eval.py.

  * the figure draws exactly the record: per column the interval and mean of the specialist
    of that combination (filled circle) and of the specialist of all three rules (open
    square, absent from its own column), and the means of the other specialists (small open
    circles, six per column and seven in column LSW), each mark inside its own column, under
    tick labels that set the combination names in math italic ($LS$);
  * the gate holds every plotted value against the macro file written in p100's own format
    (p100_cross_eval.cell_line): one number that disagrees, a missing count or a missing
    macro file is refused, and a plotted cell without a macro is compared with the record
    only and listed;
  * a missing record, a record without a cell, a verdict or direction that its interval
    does not give, and a record of another sign or generator are refused;
  * the other specialists of a column never overlap, however close their means;
  * main draws fq2_reuse only with --only fq2_reuse, reading the record and the macro file
    through arm_registry.out, and the run without --only does not call it.

Synthetic records only, written under the pytest temporary folder; nothing is trained or
evaluated, and no display is needed.
Run from the repository root:  python -B -m pytest tests/test_fq2_reuse.py -q
"""
