NAMES = ('fq1_specialists', 'fq3_time_budget', 'fq4_boundary', 'fs_convergence', 'fq2_reuse')


def _record_calls(monkeypatch):
    calls = []
    for name in NAMES:
        monkeypatch.setattr(M, name, lambda *a, _n=name: calls.append((_n, a)) or [])
    return calls


def test_the_run_without_only_does_not_draw_fq2_reuse(monkeypatch):
    for v in ('PACT_ENV', 'PACT_SEEDS', 'PACT_OUT', 'PACT_RESULTS'):
        monkeypatch.delenv(v, raising=False)
    calls = _record_calls(monkeypatch)
    monkeypatch.setattr(sys, 'argv', ['make_figures.py', '--factory-seeds', 'five'])
    monkeypatch.chdir(ROOT)
    M.main()
    called = [n for n, _ in calls]
    assert called[0] == 'fq1_specialists' and 'fq2_reuse' not in called


def test_only_fq2_reuse_draws_it_alone_from_the_registry_paths(monkeypatch):
    monkeypatch.setenv('PACT_ENV', 'exact')
    monkeypatch.setenv('PACT_SEEDS', '301-305')
    monkeypatch.setenv('PACT_OUT', 'out/exact')
    monkeypatch.delenv('PACT_RESULTS', raising=False)
    calls = _record_calls(monkeypatch)
    monkeypatch.setattr(sys, 'argv', ['make_figures.py', '--only', 'fq2_reuse'])
    monkeypatch.chdir(ROOT)
    M.main()
    ((name, (js, mac, out)),) = calls
    assert name == 'fq2_reuse'
    assert js == os.path.join(ROOT, 'out', 'exact', 'results', 'cross_eval.json')
    assert mac == os.path.join(ROOT, 'out', 'exact', 'manuscript', 'macros_crosseval.tex')
    assert out == os.path.join(ROOT, M.OUT_DEFAULT)
