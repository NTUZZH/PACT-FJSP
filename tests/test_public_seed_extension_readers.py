"""The readers of the first five seeds of the benchmark from public instances do not see the
files of the second five seeds (scripts/pub_seed_extension.py, an addition after the
five-seed result was known):

  * scripts/p89_public_family.py, the default family and --family active, writes the same
    bytes before and after every file of the 45 runs of seeds 306 to 310 is added to its tree;
  * scripts/p108_public_active_arm.py writes the same bytes, and plans the same, for its
    three-seed and five-seed readings, although its globs pubx-act-* name the policy runs
    pubx-act-s306 to -s310;
  * the macro file of the ten-seed comparison (manuscript/macros_pubseedext.tex) changes
    nothing in p89's outputs but the count of macro files its collision check read.

Synthetic trees of the existing tests (six instances per set), with the files of the second
seeds copied from the same recipe at seed s - 5. CPU only, everything under a temporary folder.
Run from the repository root:  python -m pytest tests/test_public_seed_extension_readers.py -q
"""
import json
import os
import shutil
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'scripts'))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import p108_public_active_arm as A  # noqa: E402
import p89_public_family as P  # noqa: E402
import pub_seed_extension as PSE  # noqa: E402
import test_pubact_five_seeds as T5  # noqa: E402
import test_public_family_active as TF  # noqa: E402
from test_public_family_inference import small_sets  # noqa: E402,F401  (autouse: six instances per set)

B = TF.B
FAM = P.Fam('active')


@pytest.fixture(autouse=True)
def no_results_env(monkeypatch):
    monkeypatch.delenv('PUB_RESULTS', raising=False)


def add_second_seeds(root):
    """Every file of the 45 runs of the second five seeds: a copy of the file of the same recipe
    at seed s - 5 where the tree has one, an empty file otherwise. Returns the paths."""
    made = []
    for arm, combo, s in PSE.runs():
        for src, dst in zip(PSE.files(arm, combo, s - 5), PSE.files(arm, combo, s)):
            d = os.path.join(root, dst)
            assert not os.path.exists(d)
            os.makedirs(os.path.dirname(d), exist_ok=True)
            if os.path.exists(os.path.join(root, src)):
                shutil.copy(os.path.join(root, src), d)
            else:
                open(d, 'w').close()
            made.append(dst)
    assert len(made) == 305
    return made


def p89_outputs(root, out, family):
    extra = ['--family', 'active'] if family == 'active' else []
    P.main(extra + ['--root', str(root), '--out', str(out), '--boot', str(B)])
    files = FAM.out_files if family == 'active' else P.OUT_FILES
    return {f: open(os.path.join(str(out), f), 'rb').read() for f in files}


def test_p89_outputs_unchanged_by_second_seed_files(tmp_path):
    root = TF.tree(tmp_path)
    before = {fam: p89_outputs(root, tmp_path / f'before_{fam}', fam) for fam in ('nondelay', 'active')}
    made = add_second_seeds(root)
    assert sum(os.path.getsize(os.path.join(root, f)) > 0 for f in made) > 200   # real copies
    for fam in ('nondelay', 'active'):
        assert p89_outputs(root, tmp_path / f'after_{fam}', fam) == before[fam], fam


def test_p89_reads_the_ten_seed_macro_file_only_for_its_collision_check(tmp_path):
    root = TF.tree(tmp_path)
    before = p89_outputs(root, tmp_path / 'before', 'active')
    p = os.path.join(root, 'manuscript', 'macros_pubseedext.tex')
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'w').write('% Generated by scripts/p115_public_seed_extension.py -- do not hand-edit\n'
                       '\\newcommand{\\PubSeedExtSeedN}{10}\\newcommand{\\PubSeedExtN}{+0.10}\n')
    after = p89_outputs(root, tmp_path / 'after', 'active')
    js, md, mac = FAM.out_files
    assert after[md] == before[md] and after[mac] == before[mac]
    a, b = json.loads(after[js]), json.loads(before[js])
    assert a.pop('macro_files_checked') == b.pop('macro_files_checked') + 1 and a == b


def p108_outputs(root, out, *extra):
    T5.run(root, out, *extra)
    return T5.read_outputs(out)


@pytest.mark.parametrize('seeds', ['301-303', '301-305'])
def test_p108_outputs_unchanged_by_second_seed_files(tmp_path, seeds):
    root = T5.three_tree(tmp_path)
    if seeds == '301-305':
        T5.write_later(root)
    plan = A.main(['plan', '--root', root])
    before = p108_outputs(root, tmp_path / 'before', '--seeds', seeds)
    auto = p108_outputs(root, tmp_path / 'auto')
    assert auto == before                       # auto reads the seeds the tree holds
    made = add_second_seeds(root)
    assert {os.path.normpath(f) for f in made if '/pubx-act-' in f or '+pubx-act-' in f
            or 'PUBFAMILY_pubx-act-' in f} == A.second_seed_files()
    assert A.main(['plan', '--root', root]) == plan
    assert A.SEEDS == A.THREE
    st = A.arm_state(root)
    assert st['state'] == 'complete' and not st['unexpected'], st
    assert p108_outputs(root, tmp_path / 'after', '--seeds', seeds) == before
    assert p108_outputs(root, tmp_path / 'after_auto') == before
