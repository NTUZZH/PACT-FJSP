r"""Macros for the 1800-second campaign: the solver at a literature-standard
budget, five and eight times past the training size.

Emits paper/macros_scale1800.tex from the two 80-solve cells, under the rules
fixed in FINALISATION_CHECKLIST.md before the data existed:

  ONE RULER      cross-size improvement statements use "did the search improve
                 on its own warm start"; policy comparisons use the anytime
                 convention (p39): gap = 100*(credited - policy)/policy,
                 positive = policy ahead. The two never share a sentence.
  EQUAL n        group ceilings take max over ALL 40 solves, unchanged = 0%.
  QUALIFIER      every macro here is a fixed-1800s quantity; the prose that
                 uses one must carry the qualifier.
  DISCLOSURE     improvements at the one-hour minimum resolution are counted
                 and named, never thresholded away.
  NO PARTIAL     refuses unless both cells hold all 80 solves.

The anytime trajectories let one 1800 s solve answer every smaller budget:
credited(b) = min(warm start, best incumbent recorded at or before b). Those
per-rung pooled leads feed Fig. 4(b)'s 50- and 80-module curves, and the figure
regenerator asserts its plotted values against these macros, so the figure and
the paper cannot drift apart.

Usage: python scripts/p60_scale1800.py
"""
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from macro_io import emit

REGIMES = ['N', 'L', 'S', 'W', 'LS', 'LW', 'SW', 'LSW']
SETUP = {'S', 'LS', 'SW', 'LSW'}
POLICY = 'greedy+10x25+family+jointblind-v1'
SEED_SFX = ('', '-s302', '-s303')
RUNGS = [1, 2, 5, 10, 30, 60, 120, 300, 600, 1800]
WORD = {1: 'One', 2: 'Two', 5: 'Five', 10: 'Ten', 30: 'Thirty', 60: 'Sixty',
        120: 'HundredTwenty', 300: 'ThreeHundred', 600: 'SixHundred',
        1800: 'EighteenHundred'}
SIZEW = {'50x25': 'Fifty', '80x25': 'Eighty'}
OPS = {'10x25': 220, '50x25': 1100, '80x25': 1760}
N_BOOT = 20000
MACROS = 'paper/macros_scale1800.tex'
rng = np.random.default_rng(7)

for size in ('50x25', '80x25'):
    n = len(glob.glob(f'or_solution/FAMILY/{size}_fairwarm1800s/*/*.json'))
    if n < 80:
        sys.exit(f'REFUSING: {size} at {n}/80; a partial maximum understates.')


def recs(size, r):
    out = []
    for f in sorted(glob.glob(f'or_solution/FAMILY/{size}_fairwarm1800s/{r}/*.json')):
        d = json.load(open(f))
        out.append(d)
    return out


def credited_at(d, b):
    """min(warm, best incumbent at or before wall-clock b)."""
    best = d['warm_makespan']
    for t, ub, _ in d.get('anytime', []):
        if t <= b and ub < best:
            best = ub
    return best


def policy_pooled(size, r):
    xs = []
    for s in SEED_SFX:
        p = f'test_results/FAMILY/{size}/Result_{POLICY}{s}_{r}.npy'
        if not os.path.exists(p):
            sys.exit(f'REFUSING: policy seeds missing at {size}/{r}')
        a = np.load(p)
        xs.append((a[:, 0] if a.ndim > 1 else a).astype(float))
    return np.mean(xs, axis=0)


def ci(d):
    bs = d[rng.integers(0, len(d), (N_BOOT, len(d)))].mean(axis=1)
    return float(d.mean()), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


lines = ['% auto-generated by scripts/p60_scale1800.py -- do not hand-edit',
         '% Every quantity here is measured under a FIXED 1800 s budget; prose',
         '% using one must say so. Signs: policy-vs-solver gaps are positive when',
         '% the policy is ahead (p39 convention, denominator = policy makespan).']

# ---- per-rung pooled leads, for Fig. 4(b) and its gate ----------------------
for size in ('50x25', '80x25'):
    pol = {r: policy_pooled(size, r) for r in REGIMES}
    data = {r: recs(size, r) for r in REGIMES}
    for b in RUNGS:
        gaps = []
        for r in REGIMES:
            cred = np.array([credited_at(d, b) for d in data[r]])
            n = min(len(cred), len(pol[r]))
            gaps.append(100 * (cred[:n] - pol[r][:n]) / pol[r][:n])
        m = float(np.concatenate(gaps).mean())
        lines.append(f'\\newcommand{{\\Sc{SIZEW[size]}{WORD[b]}}}{{{m:+.2f}}}')
    # the 1800 s verdict, with CI and counts
    gaps, ahead, behind = [], 0, 0
    for r in REGIMES:
        cred = np.array([credited_at(d, 1800) for d in data[r]])
        n = min(len(cred), len(pol[r]))
        g = 100 * (cred[:n] - pol[r][:n]) / pol[r][:n]
        m, lo, hi = ci(g)
        ahead += lo > 0
        behind += hi < 0
        gaps.append(g)
    m, lo, hi = ci(np.concatenate(gaps))
    w = SIZEW[size]
    lines += [f'\\newcommand{{\\Sc{w}Pooled}}{{{m:+.2f}}}'
              f'\\newcommand{{\\Sc{w}PooledAbs}}{{{abs(m):.2f}}}'
              f'\\newcommand{{\\Sc{w}PooledLo}}{{{lo:+.2f}}}'
              f'\\newcommand{{\\Sc{w}PooledHi}}{{{hi:+.2f}}}',
              f'\\newcommand{{\\Sc{w}Ahead}}{{{ahead}}}'
              f'\\newcommand{{\\Sc{w}Behind}}{{{behind}}}']

# ---- the one ruler: search vs its own warm start ----------------------------
def improvements(size, budget_dir):
    vals, one_h = [], 0
    su_vals, su_imp, su_oneh = [], 0, 0
    ns_vals = []
    for r in REGIMES:
        for f in sorted(glob.glob(f'or_solution/FAMILY/{budget_dir}/{r}/*.json')):
            d = json.load(open(f))
            o, w = d['objective'], d['warm_makespan']
            g = 100 * (w - o) / w if (o is not None and o < w - 1e-9) else 0.0
            ab = (w - o) if g > 0 else 0.0
            vals.append(g)
            if g > 0 and ab <= 1.0 + 1e-9:
                one_h += 1
            if r in SETUP:
                su_vals.append(g)
                su_imp += g > 0
                if g > 0 and ab <= 1.0 + 1e-9:
                    su_oneh += 1
            else:
                ns_vals.append(g)
    return vals, one_h, su_vals, su_imp, su_oneh, ns_vals


for size in ('50x25', '80x25'):
    vals, one_h, su, su_imp, su_oneh, ns = improvements(size, f'{size}_fairwarm1800s')
    w = SIZEW[size]
    nimp = sum(1 for v in vals if v > 0)
    lines += [
        f'\\newcommand{{\\Imp{w}N}}{{{nimp}}}'
        f'\\newcommand{{\\Imp{w}Of}}{{{len(vals)}}}'
        f'\\newcommand{{\\Imp{w}Rate}}{{{100 * nimp / len(vals):.0f}}}'
        f'\\newcommand{{\\Imp{w}OneH}}{{{one_h}}}',
        f'\\newcommand{{\\Ceil{w}}}{{{max(vals):.2f}}}',
        f'\\newcommand{{\\Ceil{w}Setup}}{{{max(su):.2f}}}'
        f'\\newcommand{{\\Ceil{w}NoSetup}}{{{max(ns):.2f}}}',
        f'\\newcommand{{\\Imp{w}SetupN}}{{{su_imp}}}'
        f'\\newcommand{{\\Imp{w}SetupOneH}}{{{su_oneh}}}',
    ]

# 10x25 rows of the same ruler (existing dirs), for the cross-size sentence
for tag, d, b in (('TenThirty', '10x25_fairwarm30s', 30),
                  ('TenThreeH', '10x25_fairwarm300s', 300)):
    vals = []
    for r in REGIMES:
        for f in sorted(glob.glob(f'or_solution/FAMILY/{d}/{r}/*.json')):
            x = json.load(open(f))
            o, w = x['objective'], x['warm_makespan']
            vals.append(100 * (w - o) / w if (o is not None and o < w - 1e-9) else 0.0)
    nimp = sum(1 for v in vals if v > 0)
    lines.append(f'\\newcommand{{\\Imp{tag}Rate}}{{{100 * nimp / len(vals):.0f}}}'
                 f'\\newcommand{{\\Ceil{tag}}}{{{max(vals):.2f}}}'
                 f'\\newcommand{{\\SPerOp{tag}}}{{{b / OPS["10x25"]:.2f}}}')
lines.append(f'\\newcommand{{\\SPerOpFifty}}{{{1800 / OPS["50x25"]:.2f}}}'
             f'\\newcommand{{\\SPerOpEighty}}{{{1800 / OPS["80x25"]:.2f}}}')
lines.append(f'\\newcommand{{\\ScBudgetSec}}{{1800}}'
             f'\\newcommand{{\\ScBudgetMin}}{{30}}'
             f'\\newcommand{{\\ScPrefixN}}{{10}}')

emit(MACROS, lines)
print(f'wrote {MACROS} ({len(lines)} lines)')
for ln in lines[4:14]:
    print('  ', ln[:96])
