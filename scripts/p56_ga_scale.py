r"""The genetic algorithm across the three shop sizes.

E5 measures the GA at the training size only, so the paper's claim that the
policy is the strongest option inside a one-second budget rests on 10x25 for
that rival while the rules and CP-SAT are measured at all three sizes. This
closes the gap: the same GA, the same budgets, the same instances the policy
and the rules were evaluated on at 20x25 and 30x25.

Estimator and conventions are p11_equivalence.py's: the mean per-instance
relative makespan gap, paired over instances, 20k-resample bootstrap on rng
seed 7. The policy side pools its three seeds; the GA is deterministic given
its own seed and budget, so there is no seed pool to match on that side, and
the comparison is one pooled policy against one GA run per cell, which is how
E5 already reports it at 10x25.

Usage: python scripts/p56_ga_scale.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import numpy as np

from macro_io import emit, refuse

REGIMES = ['N', 'L', 'S', 'W', 'LS', 'LW', 'SW', 'LSW']
SIZES = ['10x25', '20x25', '30x25']
WORD = {'10x25': 'Ten', '20x25': 'Twenty', '30x25': 'Thirty'}
NJ = {'10x25': 10, '20x25': 20, '30x25': 30}
# tag on disk -> (macro word, budget in seconds)
TIERS = [('GA1s', 'One', 1), ('GA5s', 'Five', 5), ('GA', 'Thirty', 30)]
POLICY = 'greedy+10x25+family+jointblind-v1'
SEED_SFX = ('', '-s302', '-s303')
N_BOOT = 20000
MACROS = 'paper/macros_gascale.tex'
DATA = 'results/ga_scale.json'

rng = np.random.default_rng(7)


def arr(size, tag, r):
    p = f'test_results/FAMILY/{size}/Result_{tag}_{r}.npy'
    if not os.path.exists(p):
        return None
    a = np.load(p)
    return (a[:, 0] if a.ndim > 1 else a).astype(float)


def policy(size, r):
    xs = [arr(size, f'{POLICY}{s}', r) for s in SEED_SFX]
    xs = [x for x in xs if x is not None]
    return (np.mean(xs, axis=0), len(xs)) if xs else (None, 0)


def ci(d):
    n = len(d)
    bs = d[rng.integers(0, n, (N_BOOT, n))].mean(axis=1)
    lo, hi = np.percentile(bs, [2.5, 97.5])
    return float(d.mean()), float(lo), float(hi)


cells, missing = [], []
for size in SIZES:
    for tag, word, budget in TIERS:
        gaps, nwin, nlose = [], 0, 0
        for r in REGIMES:
            a, ns = policy(size, r)
            b = arr(size, tag, r)
            if a is None or b is None:
                missing.append(f'{tag} at {size}/{r}')
                continue
            n = min(len(a), len(b))
            g = 100 * (a[:n] - b[:n]) / b[:n]
            gaps.append(g)
            _, lo, hi = ci(g)
            nwin += hi < 0
            nlose += lo > 0
        if len(gaps) != len(REGIMES):
            continue
        m, lo, hi = ci(np.concatenate(gaps))
        cells.append(dict(size=size, tier=tag, word=word, budget=budget,
                          jobs=NJ[size], mean=m, lo=lo, hi=hi,
                          win=nwin, lose=nlose, seeds=ns))

if missing:
    refuse(MACROS, 'missing GA evaluations: ' + '; '.join(missing[:8])
           + (f' (+{len(missing) - 8} more)' if len(missing) > 8 else ''))
    sys.exit(1)

lines = ['% auto-generated by scripts/p56_ga_scale.py -- do not hand-edit',
         '% The GA at three shop sizes. Negative = the policy finishes earlier;',
         '% the Abs variants are for prose that already says "ahead of".']
print(f'{"tier":8s} {"size":8s} {"gap":>8s}  {"CI":>16s}  win/loss')
for c in cells:
    key = f'Ga{c["word"]}{WORD[c["size"]]}'
    lines.append(
        f'\\newcommand{{\\{key}}}{{{c["mean"]:+.2f}}}'
        f'\\newcommand{{\\{key}Abs}}{{{abs(c["mean"]):.2f}}}'
        f'\\newcommand{{\\{key}Lo}}{{{c["lo"]:+.2f}}}'
        f'\\newcommand{{\\{key}Hi}}{{{c["hi"]:+.2f}}}'
        f'\\newcommand{{\\{key}Win}}{{{c["win"]}}}'
        f'\\newcommand{{\\{key}Lose}}{{{c["lose"]}}}')
    print(f'{c["tier"]:8s} {c["size"]:8s} {c["mean"]:+8.2f}  '
          f'[{c["lo"]:+6.2f},{c["hi"]:+6.2f}]  {c["win"]}/{c["lose"]}')

# The claim the paper makes from this: does the GA close the gap as the shop
# grows, or widen it? Emitted as a count so no sentence has to assert it.
widen = sum(1 for _, word, _ in TIERS
            if abs(next(c['mean'] for c in cells
                        if c['word'] == word and c['size'] == '30x25'))
            > abs(next(c['mean'] for c in cells
                       if c['word'] == word and c['size'] == '10x25')))
lines.append(f'\\newcommand{{\\GaScaleWiden}}{{{widen}}}'
             f'\\newcommand{{\\GaScaleTiers}}{{{len(TIERS)}}}')
print(f'\n  the policy\'s lead widens from 10 to 30 modules on {widen} of '
      f'{len(TIERS)} budgets')

emit(MACROS, lines)
os.makedirs('results', exist_ok=True)
with open(DATA, 'w') as f:
    json.dump(dict(cells=cells, sizes=SIZES, regimes=REGIMES), f, indent=1)
print(f'wrote {DATA}')
