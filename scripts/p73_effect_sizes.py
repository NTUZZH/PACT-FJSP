def write_tex():
    lines = [HEADER,
             r'\begin{tabular}{lllrrlll}', r'\toprule',
             r'Family & Comparison & Regime & $n$ & Mean gap (\%) & '
             r'Mean difference (h) [95\% CI] & $p$ (Holm) & $r$ \\',
             r'\midrule']
    prev = None
    for row in ROWS:
        fam = FAM_SHORT[row['family']]
        if prev is not None and fam != prev:
            lines.append(r'\midrule')
        prev = fam
        comp = row['comparison']
        if row['size']:
            comp += f', {row["size"].split("x")[0]} modules'
        mark = r'$^{\dagger}$' if row['family'] == 'E1/E2 superiority' else ''
        lo, hi = row['diff_ci95_h']
        lines.append(' & '.join([
            fam, comp, f'${row["regime"]}$', str(row['n']),
            num(row['mean_gap_pct'], 2),
            f'{num(row["mean_diff_h"], 2)} [{num(lo, 2)}, {num(hi, 2)}]',
            fmt_p(row['p_holm']) + mark,
            num(row['r'], 2)]) + r' \\')
    lines += [r'\midrule',
              r"\multicolumn{8}{l}{\scriptsize Sign follows each family's "
              r'estimator: E1 and E3, first minus second (E3: intervened minus '
              r'true token); E6, rule minus policy.} \\',
              r'\multicolumn{8}{l}{\scriptsize $p$: two-sided paired Wilcoxon, '
              r'Holm-adjusted within the family; $^{\dagger}$ two-sided '
              r'paired-bootstrap $p$, Holm over the superiority claims.} \\',
              r'\multicolumn{8}{l}{\scriptsize $r$: matched rank-biserial '
              r'correlation over the nonzero paired differences.} \\',
              r'\bottomrule', r'\end{tabular}']
    os.makedirs(os.path.dirname(OUT_TEX), exist_ok=True)
    with open(OUT_TEX, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {OUT_TEX} ({len(ROWS)} rows)')


def write_macros():
    out = [HEADER]
    for fam, tag in MAC.items():
        rs = [abs(r['r']) for r in ROWS if r['family'] == fam]
        if not rs:
            continue
        out.append(f'\\newcommand{{\\EffectRMin{tag}}}{{{min(rs):.2f}}}'
                   f'\\newcommand{{\\EffectRMax{tag}}}{{{max(rs):.2f}}}'
                   f'  % {fam}: smallest and largest |r| over {len(rs)} test(s)')
    emit(OUT_MAC, out)


def write_md(report, B):
    L = ['# Effect sizes of the Holm-corrected paired comparisons', '',
         f'Generated by `scripts/p73_effect_sizes.py` (scipy {scipy.__version__}, '
         f'numpy {np.__version__}); hours CI from {B} instance resamples, '
         'rng seed 7 per row.', '',
         'r = (W+ - W-)/(W+ + W-) over the nonzero paired differences, zeros '
         "dropped before ranking (scipy zero_method='wilcox', average ranks for "
         'ties). Sign follows each family\'s estimator: E1/E2 first minus '
         'second; E3 intervened minus true token; E6 rule minus policy.', '',
         '## Reproduction of the owning scripts', '']
    for fam, v in report.items():
        L.append(f'- **{fam}**: reproduced exactly = {v["reproduced_exactly"]} '
                 f'({v["compared"]}).')
        for f, s in v['sandbox_files_vs_manuscript'].items():
            L.append(f'  - sandbox `{f}` vs repository copy: {s}')
    L += ['', '## Tests', '',
          '| family | comparison | regime | n | n zero | mean gap % | '
          'mean diff h [95% CI] | W (scipy) | p raw | p Holm | r | '
          'one-sided Holm (E3) |',
          '|---|---|---|---|---|---|---|---|---|---|---|---|']
    for r in ROWS:
        lo, hi = r['diff_ci95_h']
        comp = r['comparison'] + (f', {r["size"]}' if r['size'] else '')
        one = r.get('one_sided_greater', {}).get('p_holm')
        L.append('| ' + ' | '.join([
            FAM_SHORT[r['family']], comp, r['regime'], str(r['n']),
            str(r['n_zero']), f'{r["mean_gap_pct"]:+.2f}',
            f'{r["mean_diff_h"]:+.2f} [{lo:+.2f}, {hi:+.2f}]',
            f'{r["wilcoxon_two_sided"]["statistic"]:.1f}',
            f'{r["p_raw"]:.2e}', f'{r["p_holm"]:.2e}', f'{r["r"]:+.3f}',
            '' if one is None else f'{one:.2e}']) + ' |')
    L += ['', 'E1/E2 rows: p raw and p Holm are the paired-bootstrap p of '
          'record (p11); the Wilcoxon W and r are descriptive companions on '
          'the same pooled pairing (two-sided Wilcoxon p in the JSON).', '']
    with open(OUT_MD, 'w') as f:
        f.write('\n'.join(L))
    print(f'wrote {OUT_MD}')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--boot', type=int, default=20000,
                    help='instance resamples for the hours CI (default 20000)')
    B = ap.parse_args().boot
    os.chdir(REPO)

    p11_res, p11_holm, p11_keys = family_p11(B)
    e3 = family_p17(B)
    e6 = family_p18(B)

    report, bad = verify(p11_res, p11_holm, p11_keys, e3, e6)
    for fam, v in report.items():
        print(f'{fam}: reproduced exactly = {v["reproduced_exactly"]} '
              f'({v["compared"]})')
        for f, s in v['sandbox_files_vs_manuscript'].items():
            print(f'    sandbox {f} vs repository: {s}')
    if bad:
        sys.exit('*** REFUSING TO WRITE: recomputed p-values do not match the '
                 'owning scripts:\n  ' + '\n  '.join(bad))
    if any(not np.isfinite(r['r']) for r in ROWS):
        sys.exit('*** REFUSING TO WRITE: a test has no nonzero differences, '
                 'so r is undefined')

    os.makedirs('results', exist_ok=True)
    with open(OUT_JSON, 'w') as f:
        json.dump(dict(generator='scripts/p73_effect_sizes.py',
                       scipy=scipy.__version__, numpy=np.__version__,
                       bootstrap_resamples=B, bootstrap_seed=7,
                       zero_handling="nonzero differences only "
                                     "(scipy zero_method='wilcox')",
                       verification=report, tests=ROWS), f, indent=1)
    print(f'wrote {OUT_JSON}')
    write_md(report, B)
    write_tex()
    write_macros()

    print()
    for r in ROWS:
        lo, hi = r['diff_ci95_h']
        print(f'{FAM_SHORT[r["family"]]:3s} {r["comparison"][:40]:40s} '
              f'{(r["size"] or ""):5s} {r["regime"]:4s} n={r["n"]:3d} '
              f'gap {r["mean_gap_pct"]:+6.2f}%  d {r["mean_diff_h"]:+6.2f} h '
              f'[{lo:+.2f},{hi:+.2f}]  pHolm {r["p_holm"]:.2e}  r {r["r"]:+.3f}')


if __name__ == '__main__':
    main()
