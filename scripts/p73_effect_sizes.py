r"""Effect sizes for the paired comparisons the manuscript tests with Holm.

Three families, each reproduced from the script that owns it, with the same
files, the same per-instance pairing and the same pooling over seeds:

  E1/E2 superiority family (scripts/p11_equivalence.py). Every certified
      SUPERIOR verdict of E1, E2 and E2blind. Its test of record is the
      two-sided paired-bootstrap p of the mean per-instance relative gap
      (20000 draws from one rng stream, seed 7), Holm-adjusted across the
      family. It is NOT a Wilcoxon family. The Wilcoxon statistic, its p and
      the rank-biserial r are computed here on the same pooled pairing as
      descriptive companions, and the table prints the bootstrap Holm p.
  E3 token interventions (scripts/p17_e3_multiplicity.py). Fifteen paired
      Wilcoxon tests, intervened minus true-token makespan, Holm across the
      fifteen, one-sided (did it hurt?) and two-sided. The table prints the
      two-sided Holm p; the one-sided family is kept in the JSON and the
      Markdown report.
  E6 scale transfer (scripts/p18_e6_table.py). Two-sided paired Wilcoxon of
      the policy's per-instance seed mean against the strongest rule, Holm
      across the eight regimes within each size.

Effect size: the matched-pairs rank-biserial correlation
    r = (W_plus - W_minus) / (W_plus + W_minus),
from the signed average ranks of |d| over the NONZERO paired differences.
Zero differences are dropped before ranking, which is scipy's default
zero_method='wilcox' used by all three scripts. The statistic scipy reports
(min(W_plus, W_minus) two-sided, W_plus for alternative='greater') is
asserted against the ranks computed here.

Sign: r, the mean difference in hours and the mean relative gap share one
orientation per row, that of the family's own estimator. E1/E2: first minus
second (negative = the first policy is faster). E3: intervened minus true
token (positive = the intervention slowed the policy). E6: rule minus policy
(positive = the policy is faster), as the E6 lead is printed.

Verification. Each owning script is run unchanged inside a throwaway
directory (symlinks to test_results/ and trained_network/, its own paper/),
so nothing in the repository is written. Every scipy.stats.wilcoxon call it
makes is recorded, and every p recomputed here must equal the recorded one;
the p11 bootstrap p and Holm p must equal the script's RESULTS and HOLM. The
files the scripts write in the sandbox are also compared with the
manuscript's copies, to show the stored arrays still reproduce them. Any
mismatch refuses: no output file is written.

Usage: taskset -c 8 env OMP_NUM_THREADS=1 python scripts/p73_effect_sizes.py
       [--boot N]   (resamples for the hours CI; default 20000)
"""
