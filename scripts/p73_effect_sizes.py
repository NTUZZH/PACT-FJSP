def fmt_p(p):
    if p >= 0.995:
        return '1.00'
    if p >= 0.001:
        return f'{p:.3f}'
    m, e = f'{p:.1e}'.split('e')
    return f'${m}\\times10^{{{int(e)}}}$'


def num(v, nd):
    if round(v, nd) == 0:                         # no '-0.00' or '+0.00'
        return f'{0:.{nd}f}'
    s = f'{v:+.{nd}f}'
    return s.replace('-', '$-$').replace('+', '$+$')


