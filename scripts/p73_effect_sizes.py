# ------------------------------------------------------------------ helpers
def load(path):
    if not os.path.exists(path):
        return None
    a = np.load(path)
    return (a[:, 0] if a.ndim > 1 else a).astype(float)


def holm(ps):
    """Holm-Bonferroni adjusted p-values, order preserved (as p11/p17/p18)."""
    m = len(ps)
    order = sorted(range(m), key=lambda i: ps[i])
    adj, running = [0.0] * m, 0.0
    for rank, i in enumerate(order):
        running = max(running, (m - rank) * ps[i])
        adj[i] = min(1.0, running)
    return adj


def signed_ranks(d):
    """W_plus, W_minus over the nonzero differences (zero_method='wilcox')."""
    nz = d[d != 0]
    if nz.size == 0:
        return 0.0, 0.0, 0
    rk = rankdata(np.abs(nz))                     # average ranks for ties
    return float(rk[nz > 0].sum()), float(rk[nz < 0].sum()), int(nz.size)


def rank_biserial(wp, wm):
    return (wp - wm) / (wp + wm) if wp + wm > 0 else float('nan')


def boot_mean_ci(d, B):
    """Percentile 95% CI of the mean of d under instance resampling.
    A fresh stream seeded 7 per row, so each interval is reproducible on its
    own and does not depend on the order in which rows are computed."""
    rng = np.random.default_rng(7)
    n = len(d)
    bs = np.empty(B)
    step = 2000                                   # keeps memory small
    for s in range(0, B, step):
        k = min(step, B - s)
        bs[s:s + k] = d[rng.integers(0, n, (k, n))].mean(axis=1)
    lo, hi = np.percentile(bs, [2.5, 97.5])
    return float(lo), float(hi)


def wilcoxon_block(x, y, alternative='two-sided'):
    """scipy's call as the owning scripts make it, plus the signed ranks.
    Returns the statistic, p, W_plus, W_minus and n_nonzero of d = x - y."""
    res = wilcoxon(x, y, alternative=alternative)
    wp, wm, nnz = signed_ranks(x - y)
    expect = wp if alternative == 'greater' else (
        wm if alternative == 'less' else min(wp, wm))
    if not np.isclose(float(res.statistic), expect, rtol=0, atol=1e-9):
        sys.exit(f'*** signed-rank check failed: scipy statistic '
                 f'{res.statistic} vs computed {expect} ({alternative})')
    return float(res.statistic), float(res.pvalue), wp, wm, nnz


ROWS = []          # one dict per test


def add_row(family, comparison, regime, x, y, orient, p_raw, p_holm,
            p_kind, B, extra=None, gap=None, size=None):
    """x, y: the paired vectors in the order the owning script passes them to
    its test. orient=+1 keeps d = x - y, -1 reports d = y - x."""
    d = orient * (x - y)
    st2, p2, wp, wm, nnz = wilcoxon_block(x, y)          # two-sided, x - y
    if orient < 0:
        wp, wm = wm, wp
    lo, hi = boot_mean_ci(d, B)
    row = dict(
        family=family, comparison=comparison, regime=regime, size=size,
        n=int(len(d)), n_nonzero=nnz, n_zero=int(len(d) - nnz),
        mean_diff_h=float(d.mean()), diff_ci95_h=[lo, hi],
        mean_gap_pct=float(gap if gap is not None else np.nan),
        W_plus=wp, W_minus=wm, r=rank_biserial(wp, wm),
        wilcoxon_two_sided=dict(statistic=st2, p=p2),
        p_raw=p_raw, p_holm=p_holm, p_kind=p_kind)
    if extra:
        row.update(extra)
    ROWS.append(row)
    return row


# ------------------------------------------- family 1: p11 superiority (E1/E2)
def family_p11(B):
    RES = 'test_results/FAMILY/10x25'
    rng = np.random.default_rng(7)               # p11's single stream

    def arr(tag, r):
        return load(f'{RES}/Result_{tag}_{r}.npy')

    def pooled(base, r):
        arrs = [arr(f'{base}{s}', r) for s in SEED_SUFFIXES]
        arrs = [a for a in arrs if a is not None]
        if not arrs:
            return None, 0
        return np.mean(arrs, axis=0), len(arrs)

    def ci(d, Bp=20000):                         # p11's ci(), verbatim logic
        n = len(d)
        idx = rng.integers(0, n, (Bp, n))
        bs = d[idx].mean(axis=1)
        lo, hi = np.percentile(bs, [2.5, 97.5])
        p = 2.0 * (1 + min(int((bs <= 0).sum()), int((bs >= 0).sum()))) / (Bp + 1)
        return float(d.mean()), float(lo), float(hi), min(1.0, p)

    def verdict(lo, hi, M=1.0):
        if hi < 0:
            return 'SUPERIOR'
        if -M < lo and hi < M:
            return 'EQUIVALENT'
        if hi < M:
            return 'non-inferior'
        if lo > M:
            return 'INFERIOR'
        return 'INCONCLUSIVE'

    J = 'greedy+10x25+family+jointblind-v1'
    C = 'greedy+10x25+family+joint-v1'
    res, pairs = {}, {}

    def compare(key, a_base, b_base, r):
        a, na = pooled(a_base, r)
        b, nb = pooled(b_base, r)
        if a is None or b is None or na != nb:
            sys.exit(f'*** p11 family: {key} missing or asymmetric '
                     f'({na} vs {nb} seeds); p11 itself would refuse')
        m, lo, hi, p = ci(100 * (a - b) / b)
        res[key] = (m, lo, hi, verdict(lo, hi), na, nb, p)
        pairs[key] = (a, b, a_base, b_base, na)

    # Same call order as p11, so the shared stream is consumed identically.
    for r in ['N', 'L', 'S', 'W', 'LS', 'LW']:
        compare(('E1', r), J, f'greedy+10x25+family+spec-{r}', r)
    for r in ['SW', 'LSW']:
        compare(('E2', r), J, f'greedy+10x25+family+spec-{r}', r)
    for r in ['SW', 'LSW']:
        compare(('E2blind', r), C, J, r)
    for r in ['SW', 'LSW']:                      # E2pdr draws (not in family)
        j, _ = pooled(J, r)
        pdrs = {k: arr(k, r) for k in ('FIFO', 'MOR', 'SPT', 'MWKR')}
        pdrs = {k: v for k, v in pdrs.items() if v is not None}
        if j is None or not pdrs:
            continue
        best = min(pdrs, key=lambda k: pdrs[k].mean())
        m, lo, hi, p = ci(100 * (pdrs[best] - j) / j)
        res[('E2pdr', r)] = (m, lo, hi, best, None, 1, p)

    keys = [k for k, x in res.items()
            if k[0] in ('E1', 'E2', 'E2blind') and x[3] == 'SUPERIOR']
    adj = dict(zip(keys, holm([res[k][6] for k in keys])))
    label = {'E1': 'policy vs specialist', 'E2': 'policy vs specialist',
             'E2blind': 'conditioned vs released policy'}
    for k in keys:
        a, b, a_base, b_base, ns = pairs[k]
        add_row('E1/E2 superiority', label[k[0]], k[1], a, b, +1,
                res[k][6], adj[k], 'paired-bootstrap (p11), Holm', B,
                gap=res[k][0],
                extra=dict(subfamily=k[0], seeds_pooled=ns,
                           bootstrap_gap_ci95_pct=[res[k][1], res[k][2]],
                           family_size=len(keys),
                           files=[a_base, b_base],
                           note='Wilcoxon p and r are descriptive companions '
                                'on the same pooled pairing; the test of '
                                'record is the bootstrap p.'))
    return res, adj, keys


# ---------------------------------------------- family 2: p17 E3 interventions
def family_p17(B, model='joint-v1'):
    RES = 'test_results/FAMILY/10x25'
    REGIMES = ['L', 'S', 'W', 'LS', 'LW']
    CF = {'L': 'S', 'S': 'L', 'W': 'LS', 'LS': 'W', 'LW': 'S'}
    CH = {'L': 'lag', 'S': 'setup', 'W': 'window', 'LS': 'lag-setup',
          'LW': 'lag-window'}
    INTERV = [
        ('conflicting', 'conflicting token vs true token',
         lambda m, r: f'{m}+counterfactual-{CF[r]}'),
        ('withheld', 'token withheld vs true token',
         lambda m, r: f'{m}+withhold'),
        ('full-blind', 'token and active channels removed vs true token',
         lambda m, r: f'{m}+withhold+chblind-{CH[r]}'),
    ]
    base_tag = f'greedy+10x25+family+{model}'
    cells = []
    for name, label, namer in INTERV:
        for r in REGIMES:
            base = load(f'{RES}/Result_{base_tag}_{r}.npy')
            interv = load(f'{RES}/Result_greedy+10x25+family+'
                          f'{namer(model, r)}_{r}.npy')
            if base is None or interv is None:
                sys.exit(f'*** E3 family incomplete: {name} {r} missing; '
                         'p17 would not correct a partial family')
            p1 = float(wilcoxon(interv, base, alternative='greater').pvalue)
            p2 = float(wilcoxon(interv, base).pvalue)
            cells.append((name, label, r, interv, base, p1, p2))
    q1 = holm([c[5] for c in cells])
    q2 = holm([c[6] for c in cells])
    for (name, label, r, interv, base, p1, p2), a1, a2 in zip(cells, q1, q2):
        st1 = float(wilcoxon(interv, base, alternative='greater').statistic)
        add_row('E3 token interventions', label, r, interv, base, +1,
                p2, a2, 'two-sided Wilcoxon (p17), Holm over 15', B,
                gap=float(np.mean(100 * (interv - base) / base)),
                extra=dict(intervention=name, family_size=len(cells),
                           one_sided_greater=dict(statistic=st1, p=p1,
                                                  p_holm=a1)))
    return cells, q1, q2


# ------------------------------------------------- family 3: p18 E6 transfer
def family_p18(B):
    REGIMES = ['N', 'L', 'S', 'W', 'LS', 'LW', 'SW', 'LSW']
    SIZES = ['20x25', '30x25']
    RULES = ('FIFO', 'MOR', 'SPT', 'MWKR')
    JOINT = '10x25+family+jointblind-v1'

    def arr(size, tag, r):
        return load(f'test_results/FAMILY/{size}/Result_{tag}_{r}.npy')

    def fresh_seeds(size):                       # p18's mtime rule
        out = []
        for sfx in SEED_SUFFIXES:
            ck = f'trained_network/FAMILY/{JOINT}{sfx}.pth'
            if not os.path.exists(ck):
                continue
            t0 = os.path.getmtime(ck)
            ps = [f'test_results/FAMILY/{size}/Result_greedy+{JOINT}{sfx}_{r}.npy'
                  for r in REGIMES]
            if all(os.path.exists(p) and os.path.getmtime(p) >= t0 for p in ps):
                out.append(sfx)
        return out

    seeds = {s: fresh_seeds(s) for s in SIZES}
    if len({len(v) for v in seeds.values()}) != 1 or not seeds[SIZES[0]]:
        sys.exit(f'*** E6 seed coverage unusable: {seeds}; p18 would refuse')
    out = {}
    for size in SIZES:
        tests = []
        for r in REGIMES:
            rules = {k: arr(size, k, r) for k in RULES}
            if any(v is None for v in rules.values()):
                sys.exit(f'*** E6 {size}/{r}: missing rule file')
            pol = np.stack([arr(size, f'greedy+{JOINT}{s}', r)
                            for s in seeds[size]])
            best = min(rules, key=lambda k: float(rules[k].mean()))
            bv = rules[best]
            lead = 100.0 * (bv[None, :] - pol) / pol
            x = pol.mean(axis=0)
            p = 1.0 if np.allclose(x, bv) else float(
                wilcoxon(x, bv, alternative='two-sided').pvalue)
            tests.append((r, best, x, bv, p, float(lead.mean())))
        adj = holm([t[4] for t in tests])
        for (r, best, x, bv, p, gap), a in zip(tests, adj):
            add_row('E6 scale transfer', f'policy vs {best}', r, x, bv, -1,
                    p, a, 'two-sided Wilcoxon (p18), Holm over 8 per size',
                    B, gap=gap, size=size,
                    extra=dict(best_rule=best, family_size=len(tests),
                               seeds_pooled=len(seeds[size])))
        out[size] = (tests, adj)
    return out, seeds


# ---------------------------------------------------------------- sandbox
def run_owner(script, argv=None):
    """Run an owning script unchanged in a throwaway cwd. Returns the module
    namespace, the recorded wilcoxon calls, its stdout, and the files it
    wrote (relative path -> bytes)."""
    calls = []
    orig = scipy.stats.wilcoxon

    def recorder(x, y=None, *a, **k):
        res = orig(x, y, *a, **k)
        calls.append(dict(x=np.array(x, dtype=float).copy(),
                          y=None if y is None else np.array(y, dtype=float).copy(),
                          alternative=k.get('alternative', 'two-sided'),
                          p=float(res.pvalue), stat=float(res.statistic)))
        return res

    box = tempfile.mkdtemp(prefix='p73_')
    here, old_argv = os.getcwd(), sys.argv
    ns, buf, code = {}, io.StringIO(), 0
    try:
        for d in ('test_results', 'trained_network'):
            os.symlink(os.path.join(REPO, d), os.path.join(box, d))
        os.makedirs(os.path.join(box, 'paper', 'tables'))
        os.chdir(box)
        sys.argv = [os.path.join(REPO, 'scripts', script)] + (argv or [])
        scipy.stats.wilcoxon = recorder
        with contextlib.redirect_stdout(buf):
            try:
                ns = runpy.run_path(sys.argv[0], run_name='__main__')
            except SystemExit as e:
                code = e.code
        wrote = {}
        for root, _, files in os.walk(os.path.join(box, 'paper')):
            for f in files:
                p = os.path.join(root, f)
                with open(p, 'rb') as fh:
                    wrote[os.path.relpath(p, box)] = fh.read()
    finally:
        scipy.stats.wilcoxon = orig
        sys.argv = old_argv
        os.chdir(here)
        shutil.rmtree(box, ignore_errors=True)
    if code not in (0, None):
        sys.exit(f'*** {script} refused or failed in the sandbox: {code}\n'
                 + buf.getvalue()[-2000:])
    return ns, calls, buf.getvalue(), wrote


def find_call(calls, x, y, alternative):
    for c in calls:
        if (c['alternative'] == alternative and c['y'] is not None
                and c['x'].shape == x.shape and np.array_equal(c['x'], x)
                and np.array_equal(c['y'], y)):
            return c
    return None


def same(a, b):
    return bool(np.isclose(a, b, rtol=RTOL, atol=0))


def verify(p11_res, p11_holm, p11_keys, e3, e6):
    report, bad = {}, []

    # ---- p11: bootstrap p and Holm p must equal the script's own values
    ns, _, _, wrote = run_owner('p11_equivalence.py')
    R, H = ns['RESULTS'], ns['HOLM']
    keys_ok = sorted(ns['SUPER_KEYS']) == sorted(p11_keys)
    exact = keys_ok
    for k, v in p11_res.items():
        if k not in R:
            exact = False
            bad.append(f'p11: {k} absent from the script RESULTS')
            continue
        ref = R[k]
        for i in (0, 1, 2, 6):
            if not same(v[i], ref[i]):
                exact = False
                bad.append(f'p11 {k} field {i}: {v[i]!r} vs {ref[i]!r}')
    for k in p11_keys:
        if not same(p11_holm[k], H[k]):
            exact = False
            bad.append(f'p11 Holm {k}: {p11_holm[k]!r} vs {H[k]!r}')
    files = compare_files(wrote)
    report['E1/E2 superiority'] = dict(
        reproduced_exactly=exact, family=[list(k) for k in p11_keys],
        compared=f'{len(p11_res)} bootstrap estimates and p, '
                 f'{len(p11_keys)} Holm p', sandbox_files_vs_manuscript=files)

    # ---- p17: every Wilcoxon p, both sidednesses, and Holm
    ns, calls, _, wrote = run_owner('p17_e3_multiplicity.py')
    cells, q1, q2 = e3
    exact, n = True, 0
    for (name, _, r, interv, base, p1, p2) in cells:
        for alt, mine in (('greater', p1), ('two-sided', p2)):
            c = find_call(calls, interv, base, alt)
            n += 1
            if c is None or not same(mine, c['p']):
                exact = False
                bad.append(f'p17 {name} {r} {alt}: {mine!r} vs '
                           f'{None if c is None else c["p"]!r}')
    ref1 = [c['p'] for c in calls if c['alternative'] == 'greater']
    ref2 = [c['p'] for c in calls if c['alternative'] == 'two-sided']
    h1, h2 = ns['holm'](np.array(ref1)), ns['holm'](np.array(ref2))
    if not (np.allclose(h1, q1, rtol=RTOL, atol=0)
            and np.allclose(h2, q2, rtol=RTOL, atol=0)):
        exact = False
        bad.append('p17 Holm adjustment differs')
    files = compare_files(wrote)
    report['E3 token interventions'] = dict(
        reproduced_exactly=exact, compared=f'{n} Wilcoxon p, 30 Holm p',
        sandbox_files_vs_manuscript=files)

    # ---- p18: two-sided Wilcoxon per regime and size, and Holm
    ns, calls, _, wrote = run_owner('p18_e6_table.py')
    out, _ = e6
    exact, n = True, 0
    for size, (tests, adj) in out.items():
        ref = []
        for (r, best, x, bv, p, _) in tests:
            n += 1
            if p == 1.0 and np.allclose(x, bv):
                ref.append(1.0)
                continue
            c = find_call(calls, x, bv, 'two-sided')
            if c is None or not same(p, c['p']):
                exact = False
                bad.append(f'p18 {size} {r}: {p!r} vs '
                           f'{None if c is None else c["p"]!r}')
                ref.append(np.nan)
            else:
                ref.append(c['p'])
        if not np.allclose(ns['holm'](np.array(ref)), adj, rtol=RTOL, atol=0):
            exact = False
            bad.append(f'p18 {size} Holm adjustment differs')
    files = compare_files(wrote)
    report['E6 scale transfer'] = dict(
        reproduced_exactly=exact, compared=f'{n} Wilcoxon p, {n} Holm p',
        sandbox_files_vs_manuscript=files)
    return report, bad


def compare_files(wrote):
    """Byte comparison of what an owning script wrote in the sandbox against
    the manuscript's copy. Informational: it shows whether the stored arrays
    still reproduce the files the manuscript inputs."""
    out = {}
    for rel, data in sorted(wrote.items()):
        p = os.path.join(REPO, rel)
        if not os.path.exists(p):
            out[rel] = 'absent in repository'
            continue
        with open(p, 'rb') as fh:
            out[rel] = 'identical' if fh.read() == data else 'DIFFERS'
    return out


