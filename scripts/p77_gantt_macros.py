r"""Makespans of the schedule example (Fig. S-gantt) as LaTeX macros.

Reads results/gantt_example.json (written by scripts/p74_gantt.py), checks
that each recorded makespan equals the stored per-instance result, and writes
paper/macros_gantt.tex with the two makespans in hours. It also asserts that
the LSW makespan is more than twice the N makespan, which the supplement text
states in words.

Usage (from the repository root):
  python scripts/p77_gantt_macros.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'results', 'gantt_example.json')
OUT = os.path.join(ROOT, 'paper', 'macros_gantt.tex')


def main():
    D = json.load(open(SRC))
    R = D['regimes']
    for g in ('N', 'LSW'):
        if not R[g]['matches_stored'] or R[g]['makespan'] != R[g]['stored_makespan']:
            sys.exit(f'{g}: recorded makespan does not match the stored result')
    n, lsw = R['N']['makespan'], R['LSW']['makespan']
    # The supplement says the makespan "more than doubles" on this instance.
    if not lsw > 2 * n:
        sys.exit(f'LSW makespan {lsw} is not more than twice N makespan {n}; '
                 'revise the sentence in Section sec:sm-gantt')
    lines = ['% auto-generated by scripts/p77_gantt_macros.py -- do not hand-edit',
             f'\\newcommand{{\\GanttMakespanN}}{{{n:.0f}}}  % h, regime N, instance index {D["instance_index"]}',
             f'\\newcommand{{\\GanttMakespanLSW}}{{{lsw:.0f}}}  % h, regime LSW, same instance',
             '']
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines))
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
