"""The information grid: does telling the policy more help?

Four arms, identical training protocol, differing only in what the actor is
told about the active rules, each pooled over the same three seeds and
compared with the RELEASED policy (state only) by paired per-instance gaps:

  state only                     jointblind-v1      (the released policy)
  state + global token           joint-v1           (FiLM conditioning)
  state + pair timing            jointpair          (exact setup cost and
                                                     window push per
                                                     candidate-machine pair)
  state + pair timing + token    jointpairfilm      (both additions)

Emits paper/macros_info.tex and paper/tables/info_table.tex for the
supplement's information section, plus the two summary macros the main text
prints (worst arm-vs-released mean gap; W-specialist gap of the pair arm vs
the released arm's).

Parameter counts differ by construction (+128 for the two pair input dims,
+~39k for FiLM); that is the point of the grid, not a confound: each arm is
the released architecture plus exactly the input under test.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np

RES = 'test_results/FAMILY/10x25'
REGS = ['N', 'L', 'S', 'W', 'LS', 'LW', 'SW', 'LSW']
MARGIN = 1.0
ARMS = {  # label -> (model base, seed suffixes)
    'token':     ('joint-v1', ['', '-s302', '-s303']),
    'pair':      ('jointpair', ['-s301', '-s302', '-s303']),
    'pairtoken': ('jointpairfilm', ['-s301', '-s302', '-s303']),
}
BLD = [('jointblind-v1', s) for s in ['', '-s302', '-s303']]


def pool(base, sufs, r):
    arrs = []
    for s in sufs:
        p = f'{RES}/Result_greedy+10x25+family+{base}{s}_{r}.npy'
        if not os.path.exists(p):
            return None
        arrs.append(np.load(p)[:, 0])
    return np.mean(arrs, axis=0)


def ci(d, rng):
    boots = [rng.choice(d, len(d)).mean() for _ in range(5000)]
    return float(np.percentile(boots, 2.5)), float(np.percentile(boots, 97.5))


def verdict(lo, hi):
    if -MARGIN < lo and hi < MARGIN:
        return 'EQUIVALENT'
    if hi < 0:
        return 'arm ahead'
    if lo > MARGIN:
        return 'arm INFERIOR'
    return 'inconclusive'


def main():
    rng = np.random.default_rng(31)
    rel = {r: pool('jointblind-v1', ['', '-s302', '-s303'], r) for r in REGS}
    if any(v is None for v in rel.values()):
        raise SystemExit('released-arm results missing')

    rows = []          # (arm, regime, mean, lo, hi, verdict)
    per_arm_worst = {}
    for arm, (base, sufs) in ARMS.items():
        worst = -np.inf
        for r in REGS:
            a = pool(base, sufs, r)
            if a is None:
                raise SystemExit(f'{arm} missing on {r} -- queue not finished?')
            rel_gap = 100.0 * (a - rel[r]) / rel[r]
            lo, hi = ci(rel_gap, rng)
            m = float(rel_gap.mean())
            rows.append((arm, r, m, lo, hi, verdict(lo, hi)))
            worst = max(worst, m)
        per_arm_worst[arm] = worst
        n_eq = sum(1 for x in rows if x[0] == arm and x[5] == 'EQUIVALENT')
        print(f'{arm:10s}: equivalent to released on {n_eq}/8; '
              f'worst mean gap {worst:+.2f}%')

    # the W question the review asked: does pair information close the released
    # arm's weakest regime? Compare each arm against the W SPECIALIST.
    specW = pool('spec-W', ['', '-s302', '-s303'], 'W')
    mac = ['% auto-generated by scripts/p51_info_arms.py -- do not hand-edit']
    gW_rel = 100.0 * (rel['W'] - specW) / specW
    for name, arr in [('Rel', rel['W']),
                      ('Pair', pool('jointpair',
                                    ['-s301', '-s302', '-s303'], 'W'))]:
        g = 100.0 * (arr - specW) / specW
        lo, hi = ci(g, rng)
        mac.append(f'\\newcommand{{\\InfoW{name}Delta}}{{{g.mean():+.2f}}}'
                   f'\\newcommand{{\\InfoW{name}Lo}}{{{lo:+.2f}}}'
                   f'\\newcommand{{\\InfoW{name}Hi}}{{{hi:+.2f}}}')
        print(f'W vs specialist, {name}: {g.mean():+.2f} [{lo:+.2f},{hi:+.2f}]')

    n_total_eq = sum(1 for x in rows if x[5] == 'EQUIVALENT')
    n_ahead = sum(1 for x in rows if x[5] == 'arm ahead')
    worst_all = max(per_arm_worst.values())
    mac += [f'\\newcommand{{\\InfoCellsAhead}}{{{n_ahead}}}'
            '  % cells where an information arm is AHEAD of the released policy',
            f'\\newcommand{{\\InfoArmsN}}{{{len(ARMS)}}}',
            f'\\newcommand{{\\InfoCellsEq}}{{{n_total_eq}}}'
            f'  % of {len(ARMS) * len(REGS)} arm-regime cells, equivalent to '
            'the released policy',
            f'\\newcommand{{\\InfoCells}}{{{len(ARMS) * len(REGS)}}}',
            f'\\newcommand{{\\InfoWorstGap}}{{{worst_all:+.2f}}}'
            '  % worst arm-vs-released mean gap across every cell']
    with open('paper/macros_info.tex', 'w') as f:
        f.write('\n'.join(mac) + '\n')

    ARM_TEX = {'token': 'global token (FiLM)',
               'pair': 'pair setup + window push',
               'pairtoken': 'both'}
    lines = [
        '% auto-generated by scripts/p51_info_arms.py -- do not hand-edit',
        '\\begin{tabular}{llrrl}',
        '\\toprule',
        'added input & regime & gap (\\%) & 95\\%~CI & verdict \\\\',
        '\\midrule']
    for arm in ARMS:
        first = True
        for x in [x for x in rows if x[0] == arm]:
            label = ARM_TEX[arm] if first else ''
            first = False
            lines.append(f'{label} & ${x[1]}$ & ${x[2]:+.2f}$ & '
                         f'$[{x[3]:+.2f},\\,{x[4]:+.2f}]$ & '
                         f'{x[5].lower()} \\\\')
        lines.append('\\midrule' if arm != 'pairtoken' else '\\bottomrule')
    lines.append('\\end{tabular}')
    with open('paper/tables/info_table.tex', 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'-> paper/macros_info.tex, paper/tables/info_table.tex '
          f'({n_total_eq}/{len(ARMS) * len(REGS)} cells equivalent)')


if __name__ == '__main__':
    main()
