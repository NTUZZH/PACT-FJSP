"""GA at matched short budgets -> the win-window macros (user directive
2026-08-11: the main exhibits must state WHEN this policy is the best option).

The published GA number is a 30 s run. That budget is 45x the policy's own
latency, so it answers "what does a shift-level replan get", not "who is best
inside the seconds a floor has after a disruption". This script reads the
1 s and 5 s GA ladder (eval_ga_family --tag 1s/5s), the best single rule, and
the credited CP-SAT tiers, and emits every method's paired gap TO THE
RELEASED POLICY at each short budget, pooled and split by setup-bearing vs
not. Positive = the method is worse than the policy.

Writes paper/macros_gal.tex; f5's panel (b) and the Discussion table read it.
"""
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np

RES = 'test_results/FAMILY/10x25'
REGS = ['N', 'L', 'S', 'W', 'LS', 'LW', 'SW', 'LSW']
SETUP = ('S', 'LS', 'SW', 'LSW')
BLD = ['jointblind-v1', 'jointblind-v1-s302', 'jointblind-v1-s303']


def pool_policy(r):
    return np.mean([np.load(f'{RES}/Result_greedy+10x25+family+{m}_{r}.npy')[:, 0]
                    for m in BLD], axis=0)


def load1(name, r):
    p = f'{RES}/Result_{name}_{r}.npy'
    if not os.path.exists(p):
        return None
    a = np.load(p)
    return a[:, 0] if a.ndim > 1 else a


_REPAIRED = None


def _repaired():
    """The repaired best-of-four hint cache, keyed [regime][instance]."""
    global _REPAIRED
    if _REPAIRED is None:
        with open('or_solution/FAMILY/warmstart_cache_repaired/'
                  'makespans.json') as f:
            _REPAIRED = json.load(f)
    return _REPAIRED


def cp_credited(budget, r):
    """Credited fair-warm CP-SAT at a rung, per instance. EXACTLY the
    p30/_any_credited convention: the 5 s and 30 s tiers were re-solved from
    the repaired hint (their warm_makespan IS that hint); the 1/2/10 s tiers
    are recredited against the repaired cache."""
    rerun = budget in (5, 30)
    d = (f'or_solution/FAMILY/10x25_fairwarmR{budget}s/{r}'
         if rerun else f'or_solution/FAMILY/10x25_fairwarm{budget}s/{r}')
    vals = {}
    for f in glob.glob(f'{d}/*.json'):
        j = json.load(open(f))
        x = j[0] if isinstance(j, list) else j
        obj = x.get('objective')
        obj = obj if obj is not None else np.inf
        base = min(obj, x['warm_makespan'])
        if not rerun:
            base = min(base, _repaired()[r][x['instance']]['repaired_ms'])
        vals[x['instance']] = base
    if not vals:
        return None
    return np.array([vals[f'instance_{i:03d}'] for i in range(len(vals))])


def gap(method_vals, pol):
    n = min(len(method_vals), len(pol))
    return 100.0 * (method_vals[:n] - pol[:n]) / pol[:n]


def ci(d, rng):
    boots = [rng.choice(d, len(d)).mean() for _ in range(5000)]
    return np.percentile(boots, [2.5, 97.5])


def main():
    rng = np.random.default_rng(21)
    pol = {r: pool_policy(r) for r in REGS}
    spt = {r: load1('SPT', r) for r in REGS}

    out = ['% auto-generated by scripts/p52_ga_ladder.py -- do not hand-edit']
    rows, grid = {}, {}
    for label, loader in [('GaOne', lambda r: load1('GA1s', r)),
                          ('GaFive', lambda r: load1('GA5s', r)),
                          ('GaThirty', lambda r: load1('GA', r)),
                          ('CpOne', lambda r: cp_credited(1, r)),
                          ('CpTwo', lambda r: cp_credited(2, r)),
                          ('CpFive', lambda r: cp_credited(5, r)),
                          ('CpTen', lambda r: cp_credited(10, r)),
                          ('CpThirty', lambda r: cp_credited(30, r)),
                          ('Rule', lambda r: spt[r])]:
        per = {}
        for r in REGS:
            v = loader(r)
            if v is None:
                print(f'  missing {label} {r}')
                continue
            per[r] = gap(v, pol[r])
        if len(per) != len(REGS):
            print(f'  {label}: incomplete, macros withheld')
            continue
        rows[label] = per
        allg = np.concatenate([per[r] for r in REGS])
        sg = np.concatenate([per[r] for r in SETUP])
        og = np.concatenate([per[r] for r in REGS if r not in SETUP])
        grid[label] = {'GapAll': round(float(allg.mean()), 4),
                       'GapSetup': round(float(sg.mean()), 4),
                       'GapOther': round(float(og.mean()), 4)}
        # only the macros the manuscript PRINTS go to the .tex (p9 forbids
        # unused definitions); the figure asserts against the full json grid.
        if label in ('CpOne',):   # GaOne and Rule margins are printed from p56/p78 (same convention as 8.2)
            # signed, for a gap column; unsigned, for a sentence that already
            # says "behind" or "trails by" and would otherwise print "+2.0%"
            out += [f'\\newcommand{{\\{label}GapAll}}{{{allg.mean():+.1f}}}'
                    f'\\newcommand{{\\{label}GapAllAbs}}{{{abs(allg.mean()):.1f}}}']
        print(f'{label:9s} vs policy: all {allg.mean():+.2f}  '
              f'setup {sg.mean():+.2f}  other {og.mean():+.2f}')

    # note in the log any method-regime cell inside 5 s that is ahead of the
    # policy; the exhibits' win-window claim depends on there being none.
    short = [k for k in ('GaOne', 'GaFive', 'CpOne', 'CpTwo', 'CpFive', 'Rule')
             if k in rows]
    cells_ahead = [(k, r) for k in short for r in REGS
                   if rows[k][r].mean() < 0]
    for k, r in cells_ahead:
        print(f'  NOTE: {k} ahead of the policy on {r} '
              f'({rows[k][r].mean():+.2f}%)')

    with open('paper/macros_gal.tex', 'w') as f:
        f.write('\n'.join(out) + '\n')
    with open('results/ga_ladder_gaps.json', 'w') as f:
        json.dump(grid, f, indent=1)
    print(f'-> paper/macros_gal.tex, results/ga_ladder_gaps.json '
          f'({len(cells_ahead)} short-budget cells ahead of the policy)')


if __name__ == '__main__':
    main()
