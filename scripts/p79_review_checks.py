"""P79: three evaluation-only checks on the released policy, one macro file each.

--part lswspec   Is one specialist trained on the hardest composition (all three
                 rules, LSW) enough for every regime? The LSW specialists
                 (three seeds) are evaluated on all eight regimes in the
                 same-campaign folder 10x25_blindref, next to the released
                 policy, the per-regime specialists and the four rules.
                 -> paper/macros_lswspec.tex
--part fifteen   The capacity-halved 15-station cells at 50 and 80 modules: the
                 released policy (three seeds) against the per-instance best of
                 the four rules. -> paper/macros_fifteen.tex
--part masktol   The non-delay mask compares machine-free times on a normalized
                 axis, which drops exact ties. A tie-tolerant comparison
                 (PACT_MASK_TOL=1, no retraining) is evaluated for the released
                 policy, the rules and the specialists in 10x25_masktol (and the
                 policy and SPT on the 80x25 prefix in 80x25_masktol), against
                 the published arrays. -> paper/macros_masktol.tex
--part repaired  The single-rule control (jointblind-nlsw, three seeds) and the
                 released policy against the REPAIRED rule pool, the per-instance
                 best of the four rules with job selection restricted to the
                 policy's mask (or_solution/FAMILY/warmstart_cache_repaired, the
                 CP-SAT hint), in 10x25_blindref. -> paper/macros_repaired.tex

Estimator throughout (p11/p34): per-instance relative gap in percent, policy
arms averaged over their three seeds per instance, mean with a 95% percentile
bootstrap over instances (20,000 resamples, numpy default_rng(7)). A missing
seed or rule is a refusal, never a partial result.

Usage: python scripts/p79_review_checks.py --part {lswspec,fifteen,masktol}
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np  # noqa: E402

from macro_io import emit  # noqa: E402

B = 20000
MARGIN = 1.0
R8 = ['N', 'L', 'S', 'W', 'LS', 'LW', 'SW', 'LSW']
RULES = ['FIFO', 'MOR', 'SPT', 'MWKR']
SEEDS = ['', '-s302', '-s303']
PACT = 'greedy+10x25+family+jointblind-v1'


def _nz(x):
    v = round(float(x), 2)
    return 0.0 if v == 0 else v


def arr(d, tag, r):
    p = f'test_results/FAMILY/{d}/Result_{tag}_{r}.npy'
    if not os.path.exists(p):
        sys.exit(f'REFUSING: missing {p}')
    a = np.load(p)
    return (a[:, 0] if a.ndim > 1 else a).astype(float)


def pooled(d, base, r):
    return np.mean([arr(d, base + s, r) for s in SEEDS], axis=0)


def pool(d, r):
    return np.min(np.stack([arr(d, x, r) for x in RULES]), axis=0)


def ci(x):
    rng = np.random.default_rng(7)
    idx = rng.integers(0, len(x), (B, len(x)))
    lo, hi = np.percentile(x[idx].mean(axis=1), [2.5, 97.5])
    return float(x.mean()), float(lo), float(hi)


def trio(name, m, lo, hi, cmt):
    return (f'\\newcommand{{\\{name}}}{{{_nz(m):+.2f}}}'
            f'\\newcommand{{\\{name}Lo}}{{{_nz(lo):+.2f}}}'
            f'\\newcommand{{\\{name}Hi}}{{{_nz(hi):+.2f}}}  % {cmt}')


def cell(m, lo, hi):
    return f'${_nz(m):+.2f}$ & \\footnotesize{{$[{_nz(lo):+.2f},\\,{_nz(hi):+.2f}]$}}'


def write_table(path, gen, header_cells, rows):
    """rows: list of (label, [cell strings]); every value comes from this script."""
    ncol = len(header_cells)
    with open(path, 'w') as f:
        f.write(f'% auto-generated by scripts/p79_review_checks.py ({gen}) -- do not hand-edit\n')
        f.write('\\begin{tabular}{l' + 'r@{\\,}l' * ncol + '}\n\\toprule\n')
        f.write('regime & ' + ' & '.join(f'\\multicolumn{{2}}{{c}}{{{h}}}' for h in header_cells)
                + '\\\\\n\\midrule\n')
        for i, (lab, cells) in enumerate(rows):
            if lab == 'pooled':
                f.write('\\midrule\n')
            f.write(f'{lab} & ' + ' & '.join(cells) + '\\\\\n')
        f.write('\\bottomrule\n\\end{tabular}\n')
    print(f'wrote {path}')


def part_lswspec():
    D, LSW = '10x25_blindref', 'greedy+10x25+family+spec-LSW'
    lines, allg, behind_pool, equiv, rows = [], [], [], [], []
    for r in R8:
        a = pooled(D, LSW, r)
        row = []
        g = 100 * (a - pooled(D, PACT, r)) / pooled(D, PACT, r)
        allg.append(g)
        m, lo, hi = ci(g)
        lines.append(trio(f'Lswsp{r}', m, lo, hi,
                          f'LSW specialist vs released policy on {r} (%, + = specialist behind)'))
        row.append(cell(m, lo, hi))
        if -MARGIN < lo and hi < MARGIN:
            equiv.append(r)
        q = pool(D, r)
        mq, loq, hiq = ci(100 * (a - q) / q)
        lines.append(trio(f'Lswsp{r}Pool', mq, loq, hiq,
                          f'LSW specialist vs rule pool on {r} (%, + = specialist behind)'))
        if loq > 0:
            behind_pool.append(r)
        if r != 'LSW':
            s = pooled(D, f'greedy+10x25+family+spec-{r}', r)
            ms, los, his = ci(100 * (a - s) / s)
            lines.append(trio(f'Lswsp{r}Own', ms, los, his,
                              f'LSW specialist vs the {r} specialist on {r} (%)'))
            row.append(cell(ms, los, his))
        else:
            row.append('\\multicolumn{2}{c}{(itself)}')
        row.append(cell(mq, loq, hiq))
        rows.append((f'${r}$', row))
        print(f'{r:4s} vs PACT {m:+.2f} [{lo:+.2f},{hi:+.2f}]  vs pool {mq:+.2f} [{loq:+.2f},{hiq:+.2f}]')
    m, lo, hi = ci(np.concatenate(allg))
    lines.append(trio('LswspPooled', m, lo, hi, 'pooled over the eight regimes'))
    rows.append(('pooled', [cell(m, lo, hi), '&', '&']))
    write_table('paper/tables/lswspec_table.tex', '--part lswspec',
                ['vs PACT', 'vs own specialist', 'vs rule pool'], rows)
    lines.append(f'\\newcommand{{\\LswspEquivN}}{{{len(equiv)}}}  % regimes inside the +-1% margin: {" ".join(equiv)}')
    lines.append(f'\\newcommand{{\\LswspBehindPoolN}}{{{len(behind_pool)}}}  % regimes where the LSW specialist is behind the rule pool, CI clear of zero: {" ".join(behind_pool)}')
    print('pooled', round(m, 2), round(lo, 2), round(hi, 2), 'equiv', equiv, 'behind pool', behind_pool)
    emit('paper/macros_lswspec.tex', lines, header='Generated by scripts/p79_review_checks.py --part lswspec')


def part_fifteen():
    lines, cols = [], {}
    for size, word in (('50x15', 'Fifty'), ('80x15', 'Eighty')):
        allg, clear, behind = [], [], []
        cols[size] = []
        for r in R8:
            p, q = pooled(size, PACT, r), pool(size, r)
            g = 100 * (q - p) / p
            allg.append(g)
            m, lo, hi = ci(g)
            lines.append(trio(f'Fift{word}{r}', m, lo, hi,
                              f'{size}: rule pool vs released policy on {r} (%, + = policy ahead)'))
            cols[size].append(cell(m, lo, hi))
            if lo > 0:
                clear.append(r)
            if hi < 0:
                behind.append(r)
        m, lo, hi = ci(np.concatenate(allg))
        lines.append(trio(f'Fift{word}Pooled', m, lo, hi, f'{size} pooled over regimes'))
        cols[size].append(cell(m, lo, hi))
        lines.append(f'\\newcommand{{\\Fift{word}ClearN}}{{{len(clear)}}}  % regimes with the interval above zero: {" ".join(clear)}')
        lines.append(f'\\newcommand{{\\Fift{word}BehindN}}{{{len(behind)}}}  % regimes with the policy behind, interval below zero')
        n = len(allg[0])
        lines.append(f'\\newcommand{{\\Fift{word}Inst}}{{{n}}}  % instances per regime')
        print(size, 'pooled', round(m, 2), round(lo, 2), round(hi, 2), 'clear', clear, 'behind', behind, 'n', n)
    rows = [(f'${r}$' if r != 'pooled' else r, [cols['50x15'][i], cols['80x15'][i]])
            for i, r in enumerate(R8 + ['pooled'])]
    write_table('paper/tables/fifteen_table.tex', '--part fifteen',
                ['50 modules', '80 modules'], rows)
    emit('paper/macros_fifteen.tex', lines, header='Generated by scripts/p79_review_checks.py --part fifteen')


def part_masktol():
    A, T = '10x25', '10x25_masktol'
    lines = []
    dp, ds, g0, g1, clear, trows = [], [], [], [], [], []
    for r in R8:
        p0, p1 = pooled(A, PACT, r), pooled(T, PACT, r)
        s0, s1 = arr(A, 'SPT', r), arr(T, 'SPT', r)
        q0, q1 = pool(A, r), pool(T, r)
        dp.append(100 * np.mean((p1 - p0) / p0))
        ds.append(100 * np.mean((q1 - q0) / q0))
        a0, a1 = 100 * (q0 - p0) / p0, 100 * (q1 - p1) / p1
        g0.append(a0); g1.append(a1)
        m, lo, hi = ci(a1)
        if lo > 0:
            clear.append(r)
        lines.append(trio(f'Mtol{r}', m, lo, hi, f'tie-tolerant mask: rule pool vs policy on {r} (%, + = policy ahead)'))
        m0r, lo0r, hi0r = ci(a0)
        trows.append((f'${r}$', f'${_nz(dp[-1]):+.2f}$', f'${_nz(ds[-1]):+.2f}$',
                      cell(m0r, lo0r, hi0r), cell(m, lo, hi)))
    m0, lo0, hi0 = ci(np.concatenate(g0)); m1, lo1, hi1 = ci(np.concatenate(g1))
    lines.append(trio('MtolPooledPub', m0, lo0, hi0, 'published mask, pooled'))
    lines.append(trio('MtolPooled', m1, lo1, hi1, 'tie-tolerant mask, pooled'))
    with open('paper/tables/masktol_table.tex', 'w') as f:
        f.write('% auto-generated by scripts/p79_review_checks.py (--part masktol) -- do not hand-edit\n')
        f.write('\\begin{tabular}{lrrr@{\\,}lr@{\\,}l}\n\\toprule\n')
        f.write('regime & policy change & rule-pool change & \\multicolumn{2}{c}{lead, published mask}'
                ' & \\multicolumn{2}{c}{lead, tie-tolerant mask}\\\\\n\\midrule\n')
        for lab, a_, b_, c_, d_ in trows:
            f.write(f'{lab} & {a_} & {b_} & {c_} & {d_}\\\\\n')
        f.write('\\midrule\n')
        f.write(f'pooled & & & {cell(m0, lo0, hi0)} & {cell(m1, lo1, hi1)}\\\\\n')
        f.write('\\bottomrule\n\\end{tabular}\n')
    print('wrote paper/tables/masktol_table.tex')
    lines.append(f'\\newcommand{{\\MtolPolicyShiftMin}}{{{_nz(min(dp)):+.2f}}}\\newcommand{{\\MtolPolicyShiftMax}}{{{_nz(max(dp)):+.2f}}}  % change of the policy mean makespan per regime (%)')
    lines.append(f'\\newcommand{{\\MtolPoolShiftMin}}{{{_nz(min(ds)):+.2f}}}\\newcommand{{\\MtolPoolShiftMax}}{{{_nz(max(ds)):+.2f}}}  % change of the rule-pool mean makespan per regime (%)')
    lines.append(f'\\newcommand{{\\MtolClearN}}{{{len(clear)}}}  % regimes with the policy ahead, interval above zero')
    print('policy shift', np.round(dp, 2), 'pool shift', np.round(ds, 2))
    print('pooled lead', round(m0, 2), '->', round(m1, 2), [round(lo1, 2), round(hi1, 2)], 'clear', clear)
    # specialists: equivalence of the released policy with the specialists, before and after
    e0, e1 = [], []
    for r in R8:
        sp = f'greedy+10x25+family+spec-{r}'
        for d, acc in ((A, e0), (T, e1)):
            p, s = pooled(d, PACT, r), pooled(d, sp, r)
            acc.append(100 * (p - s) / s)
    for nm, e in (('MtolSpecPub', e0), ('MtolSpec', e1)):
        m, lo, hi = ci(np.concatenate(e))
        lines.append(trio(nm, m, lo, hi, 'policy vs specialists pooled over regimes (%, + = policy behind)'))
        print(nm, round(m, 2), round(lo, 2), round(hi, 2))
    # 80x25 prefix: policy and SPT
    A8, T8 = '80x25', '80x25_masktol'
    g0, g1 = [], []
    for r in R8:
        p0 = pooled(A8, PACT, r)[:10]; p1 = pooled(T8, PACT, r)
        s0 = arr(A8, 'SPT', r)[:10]; s1 = arr(T8, 'SPT', r)
        g0.append(100 * (s0 - p0) / p0); g1.append(100 * (s1 - p1) / p1)
    m0, lo0, hi0 = ci(np.concatenate(g0)); m1, lo1, hi1 = ci(np.concatenate(g1))
    lines.append(trio('MtolEightyPub', m0, lo0, hi0, '80x25 prefix, SPT vs policy, published mask'))
    lines.append(trio('MtolEighty', m1, lo1, hi1, '80x25 prefix, SPT vs policy, tie-tolerant mask'))
    print('80x25 SPT lead', round(m0, 2), '->', round(m1, 2), [round(lo1, 2), round(hi1, 2)])
    emit('paper/macros_masktol.tex', lines, header='Generated by scripts/p79_review_checks.py --part masktol')


def part_repaired():
    D = '10x25_blindref'
    NL = 'greedy+10x25+family+jointblind-nlsw'
    lines, nl_ahead, pa_ahead, rows = [], [], [], []
    for r in R8:
        rep = np.array([float(np.load(
            f'or_solution/FAMILY/warmstart_cache_repaired/{r}/instance_{i:03d}.npz',
            allow_pickle=True)['ms']) for i in range(100)])
        if np.any(rep > pool(D, r) + 1e-6):
            sys.exit(f'REFUSING: repaired pool worse than textbook pool on {r}')
        nl = np.mean([arr(D, f'{NL}-s30{k}', r) for k in (1, 2, 3)], axis=0)
        pa = pooled(D, PACT, r)
        m, lo, hi = ci(100 * (rep - nl) / nl)
        lines.append(trio(f'Rep{r}Nlsw', m, lo, hi,
                          f'repaired pool vs single-rule control on {r} (%, + = control ahead)'))
        if lo > 0:
            nl_ahead.append(r)
        m2, lo2, hi2 = ci(100 * (rep - pa) / pa)
        lines.append(trio(f'Rep{r}Pact', m2, lo2, hi2,
                          f'repaired pool vs released policy on {r} (%, + = policy ahead)'))
        if lo2 > 0:
            pa_ahead.append(r)
        q = pool(D, r)
        mt, lot, hit = ci(100 * (q - nl) / nl)
        rows.append((f'${r}$', [cell(mt, lot, hit), cell(m, lo, hi), cell(m2, lo2, hi2)]))
        print(f'{r:4s} control lead {m:+.2f} [{lo:+.2f},{hi:+.2f}]  policy lead {m2:+.2f} [{lo2:+.2f},{hi2:+.2f}]')
    held = [r for r in nl_ahead if r in ('LS', 'LW', 'SW', 'LSW')]
    lines.append(f'\\newcommand{{\\RepNlswAheadN}}{{{len(nl_ahead)}}}  % control ahead of the repaired pool, interval above zero: {" ".join(nl_ahead)}')
    lines.append(f'\\newcommand{{\\RepNlswHeldAheadN}}{{{len(held)}}}  % of them held out')
    lines.append(f'\\newcommand{{\\RepPactAheadN}}{{{len(pa_ahead)}}}  % released policy ahead of the repaired pool: {" ".join(pa_ahead)}')
    print('control ahead', nl_ahead, 'policy ahead', pa_ahead)
    write_table('paper/tables/repaired_table.tex', '--part repaired',
                ['control, textbook pool', 'control, repaired pool', 'PACT, repaired pool'], rows)
    emit('paper/macros_repaired.tex', lines, header='Generated by scripts/p79_review_checks.py --part repaired')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--part', required=True, choices=['lswspec', 'fifteen', 'masktol', 'repaired'])
    {'lswspec': part_lswspec, 'fifteen': part_fifteen, 'masktol': part_masktol,
     'repaired': part_repaired}[ap.parse_args().part]()
