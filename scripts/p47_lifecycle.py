"""Reconfiguration-lifecycle accounting. Measured quantities only.

Walks the rule-change sequence a plant might see over its life,
N -> L -> LS -> LSW -> W -> SW, and counts what each deployment style must do
at each change. No monetary figures; every number traces to a measured
artifact:

  per-specialist training hours  macros_cost.tex \\SpecHours (uncontended min)
  one-policy training hours      macros_cost.tex \\JointHours (already spent
                                 before the first change; the lifecycle adds 0)
  checkpoint sizes               macros_exposure.tex \\BlindKiB / \\SpecKiB
  workstation latency            results/policy_latency_cpu.json (4 cores)
  controller-class proxy         results/policy_latency_cpu_2core_blind.json
                                 (2 pinned cores, thread-capped, blind model)

Writes paper/macros_lifecycle.tex.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

SEQUENCE = ['N', 'L', 'LS', 'LSW', 'W', 'SW']


def macro(path, name):
    txt = open(path).read()
    m = re.search(r'\\newcommand\{\\%s\}\{([^}]*)\}' % name, txt)
    if not m:
        raise SystemExit(f'{name} not found in {path}')
    return m.group(1)


def main():
    spec_h = float(macro('paper/macros_cost.tex', 'SpecHours'))
    joint_h = float(macro('paper/macros_cost.tex', 'JointHours'))

    # catalogue: one NEW specialist per regime not yet in the catalogue;
    # the base shop N needs none.
    seen, trainings = set(), 0
    for reg in SEQUENCE:
        if reg != 'N' and reg not in seen:
            trainings += 1
            seen.add(reg)
    cat_hours = trainings * spec_h

    with open('results/policy_latency_cpu_2core_blind.json') as f:
        edge = json.load(f)
    edge_s = edge['worst_regime_median_s']
    edge_cores = edge['cores']
    assert edge['model'].endswith('jointblind-v1'), edge['model']

    n_changes = len(SEQUENCE) - 1        # transitions after the initial regime
    lines = [
        '% auto-generated by scripts/p47_lifecycle.py -- do not hand-edit',
        f'\\newcommand{{\\LifeSeq}}{{$N \\to L \\to LS \\to LSW \\to W \\to SW$}}',
        f'\\newcommand{{\\LifeChanges}}{{{n_changes}}}',
        f'\\newcommand{{\\LifeCatTrainings}}{{{trainings}}}',
        f'\\newcommand{{\\LifeCatHours}}{{{cat_hours:.1f}}}',
        f'\\newcommand{{\\EdgeCores}}{{{edge_cores}}}',
        f'\\newcommand{{\\EdgeSec}}{{{edge_s:.2f}}}',
    ]
    with open('paper/macros_lifecycle.tex', 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('\n'.join(lines))
    print(f'[p47] lifecycle: {n_changes} changes, catalogue trains '
          f'{trainings} new specialists ({cat_hours:.1f} GPU-h at the measured '
          f'{spec_h}/specialist); one-policy trains 0 (its {joint_h} GPU-h '
          f'predate the first change). Edge proxy: {edge_s:.2f}s on '
          f'{edge_cores} cores.')


if __name__ == '__main__':
    main()
