r"""The rule-change table: PACT against the specialist still in service when
one timing rule is added.

Reads results/coverage_lag.json (written by p54_coverage_lag.py): for each of
the twelve pairs (regime the specialist was trained on -> regime reached by
adding one rule), the mean per-instance relative makespan gap of the PACT policy
to that specialist on the new regime's instances, its 95% paired-bootstrap CI,
the Holm-adjusted p value, and the joint_ahead flag (CI below zero and Holm
p < alpha). Negative gap = PACT finishes earlier.

The count, the ahead count and the pooled mean must equal \StaleN, \StaleAhead
and \StaleMean in paper/macros_stale.tex (same source); the script asserts it.

Writes paper/tables/rulechange_table.tex and paper/macros_rulechange.tex.
Usage: python3 scripts/p63_rulechange_table.py
"""
import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import numpy as np

from macro_io import emit, refuse

DATA = 'results/coverage_lag.json'
STALE = 'paper/macros_stale.tex'
MACROS = 'paper/macros_rulechange.tex'
TABLE = 'paper/tables/rulechange_table.tex'

if not os.path.exists(DATA):
    refuse(MACROS, f'{DATA} is missing; run scripts/p54_coverage_lag.py')
d = json.load(open(DATA))
pairs = d['pairs']
need = {'held', 'target', 'mean', 'lo', 'hi', 'p_holm', 'joint_ahead', 'n'}
if not pairs or any(need - set(p) for p in pairs):
    refuse(MACROS, f'{DATA} has no pairs or pairs without {sorted(need)}')
# joint_ahead must be what p54 says it is: CI entirely below zero AND Holm p < alpha.
for p in pairs:
    flag = bool(p['hi'] < 0 and p['p_holm'] < d['alpha'])
    if flag != p['joint_ahead']:
        refuse(MACROS, f'joint_ahead flag inconsistent for {p["held"]}->{p["target"]}')

n = len(pairs)
ahead = sum(p['joint_ahead'] for p in pairs)
# Pooled mean over all pair-instances. Every pair has the same n, so this equals
# the mean of the pair means; p54 computes it from the concatenated gaps.
if len({p['n'] for p in pairs}) != 1:
    refuse(MACROS, 'pairs differ in instance count; the pooled mean would need weights')
mean = float(np.mean([p['mean'] for p in pairs]))
if abs(mean - d['pooled']['mean']) > 1e-9:
    refuse(MACROS, f'pooled mean {mean} != coverage_lag.json pooled {d["pooled"]["mean"]}')
best = min(pairs, key=lambda p: p['mean'])      # PACT's largest lead
least = max(pairs, key=lambda p: p['mean'])     # PACT's smallest lead / largest deficit

# ------------------------------------------------------------ cross-check stale
st = open(STALE).read()


def stale(name):
    m = re.search(r'\\newcommand\{\\' + name + r'\}\{([^}]*)\}', st)
    if not m:
        refuse(MACROS, f'\\{name} not found in {STALE}')
    return m.group(1)


checks = [('StaleN', str(n)), ('StaleAhead', str(ahead)),
          ('StaleMean', f'{mean:+.2f}'), ('StaleWorst', f'{best["mean"]:+.2f}'),
          ('StaleWorstHeld', best['held']), ('StaleWorstTarget', best['target'])]
bad = [f'\\{k}: stale file {stale(k)!r}, here {v!r}' for k, v in checks if stale(k) != v]
if bad:
    refuse(MACROS, 'disagreement with macros_stale.tex:\n  ' + '\n  '.join(bad))
print(f'cross-check: \\StaleN={n}, \\StaleAhead={ahead}, \\StaleMean={mean:+.2f} '
      f'and the largest lead match {STALE}')

# ------------------------------------------------------------ table


def added_rule(held, tgt):
    base = '' if held == 'N' else held
    extra = [c for c in tgt if c not in base]
    if len(extra) != 1:
        refuse(MACROS, f'{held}->{tgt} does not add exactly one rule')
    return extra[0]


rows = []
md = ['| previous regime | new regime (rule added) | gap (%) [95% CI] | Holm p | verdict |',
      '|---|---|---|---|---|']
prev = None
for p in pairs:
    rule = added_rule(p['held'], p['target'])
    verdict = 'PACT ahead' if p['joint_ahead'] else 'not significant'
    if prev is not None and p['held'] != prev:
        rows.append(r'\addlinespace')
    prev = p['held']
    rows.append(f'{p["held"]} & {p["target"]} (+{rule}) & '
                f'${p["mean"]:+.2f}$ [${p["lo"]:+.2f}$, ${p["hi"]:+.2f}$] & '
                f'{verdict} \\\\')
    md.append(f'| {p["held"]} | {p["target"]} (+{rule}) | {p["mean"]:+.2f} '
              f'[{p["lo"]:+.2f}, {p["hi"]:+.2f}] | {p["p_holm"]:.4f} | {verdict} |')

head = [r'\begin{tabular}{llcl}', r'\toprule',
        r'previous regime & new regime (rule added) & gap (\%) [95\% CI] & verdict \\',
        r'\midrule']
foot = [r'\bottomrule', r'\end{tabular}']

# ------------------------------------------------------------ macros
lines = ['% auto-generated by scripts/p63_rulechange_table.py -- do not hand-edit',
         '% PACT vs the specialist still in service after one rule is added.',
         '% Source: results/coverage_lag.json (p54). Negative = PACT faster.',
         f'\\newcommand{{\\RuleChangeN}}{{{n}}}'
         f'\\newcommand{{\\RuleChangeAhead}}{{{ahead}}}'
         f'\\newcommand{{\\RuleChangeNotSep}}{{{n - ahead}}}'
         '  % pairs; pairs with PACT ahead after Holm; pairs not significant',
         f'\\newcommand{{\\RuleChangeMean}}{{{mean:+.2f}}}'
         f'\\newcommand{{\\RuleChangeMeanAbs}}{{{abs(mean):.2f}}}'
         '  % mean gap over all pairs (%)',
         f'\\newcommand{{\\RuleChangeBest}}{{{best["mean"]:+.2f}}}'
         f'\\newcommand{{\\RuleChangeBestAbs}}{{{abs(best["mean"]):.2f}}}'
         f'\\newcommand{{\\RuleChangeBestHeld}}{{{best["held"]}}}'
         f'\\newcommand{{\\RuleChangeBestTarget}}{{{best["target"]}}}'
         '  % largest PACT lead (most negative gap) and its pair',
         f'\\newcommand{{\\RuleChangeLeast}}{{{least["mean"]:+.2f}}}'
         f'\\newcommand{{\\RuleChangeLeastHeld}}{{{least["held"]}}}'
         f'\\newcommand{{\\RuleChangeLeastTarget}}{{{least["target"]}}}'
         f'\\newcommand{{\\RuleChangeLeastLo}}{{{least["lo"]:+.2f}}}'
         f'\\newcommand{{\\RuleChangeLeastHi}}{{{least["hi"]:+.2f}}}'
         '  % least favourable pair for PACT (largest gap) and its CI']

mine = set(re.findall(r'\\newcommand\{\\([A-Za-z]+)\}', '\n'.join(lines)))
for f in glob.glob('paper/macros_*.tex') + ['paper/macros.tex']:
    if os.path.abspath(f) == os.path.abspath(MACROS):
        continue
    clash = mine & set(re.findall(r'\\newcommand\{\\([A-Za-z]+)\}', open(f).read()))
    if clash:
        refuse(MACROS, f'macro name collision with {f}: {sorted(clash)}')

emit(MACROS, lines)
os.makedirs('paper/tables', exist_ok=True)
with open(TABLE, 'w') as f:
    f.write('% auto-generated by scripts/p63_rulechange_table.py -- do not hand-edit\n')
    f.write('% gap = mean per-instance relative makespan gap of PACT to the specialist\n')
    f.write('% trained on the previous regime, on the new regime; negative = PACT faster.\n')
    f.write('% PACT ahead = 95% CI below zero and Holm-adjusted p < '
            f'{d["alpha"]}.\n')
    f.write('\n'.join(head + rows + foot) + '\n')
print(f'wrote {TABLE}')
print('\n'.join(md))
print(f'PACT ahead on {ahead} of {n}; mean {mean:+.2f}%; largest lead '
      f'{best["held"]}->{best["target"]} {best["mean"]:+.2f}%; least favourable '
      f'{least["held"]}->{least["target"]} {least["mean"]:+.2f}%')
