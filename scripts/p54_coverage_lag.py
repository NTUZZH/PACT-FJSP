r"""The coverage lag: what a catalogue schedules with while its next specialist
is being trained and certified.

A catalogue covers a regime only once that regime's specialist exists and has
been validated. Until then the plant schedules the new rules with the
specialist it already has, which was trained for the rules in force before the
change. This script measures that interval: for every regime reached by adding
one rule to the regime a specialist was trained on, the joint policy against
that specialist, on the new regime's instances.

Estimator, pooling and refusal conventions are p11_equivalence.py's. The
verdicts are a family of discoveries, so their two-sided bootstrap p values are
Holm-adjusted across all pairs.

Usage: python scripts/p54_coverage_lag.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import numpy as np

from macro_io import emit, refuse

# specialist trained on -> the regimes one added rule away from it
NEXT = {'N': ['L', 'S', 'W'], 'L': ['LS', 'LW'], 'S': ['LS', 'SW'],
        'W': ['LW', 'SW'], 'LS': ['LSW'], 'LW': ['LSW'], 'SW': ['LSW']}
RES = '10x25'
JOINT = 'greedy+10x25+family+jointblind-v1'
SEED_SFX = ('', '-s302', '-s303')
ALPHA = 0.05
N_BOOT = 20000
MACROS = 'paper/macros_stale.tex'
DATA = 'results/coverage_lag.json'

rng = np.random.default_rng(7)


def arr(tag, r):
    p = f'test_results/FAMILY/{RES}/Result_{tag}_{r}.npy'
    if not os.path.exists(p):
        return None
    a = np.load(p)
    return (a[:, 0] if a.ndim > 1 else a).astype(float)


def pooled(base, r):
    xs = [arr(f'{base}{s}', r) for s in SEED_SFX]
    xs = [x for x in xs if x is not None]
    return (np.mean(xs, axis=0), len(xs)) if xs else (None, 0)


def ci(d):
    n = len(d)
    bs = d[rng.integers(0, n, (N_BOOT, n))].mean(axis=1)
    lo, hi = np.percentile(bs, [2.5, 97.5])
    p = 2.0 * (1 + min(int((bs <= 0).sum()), int((bs >= 0).sum()))) / (N_BOOT + 1)
    return float(d.mean()), float(lo), float(hi), min(1.0, p)


def holm(ps):
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    out = [0.0] * len(ps)
    run = 0.0
    for rank, i in enumerate(order):
        run = max(run, (len(ps) - rank) * ps[i])
        out[i] = min(1.0, run)
    return out


pairs, asym, missing = [], [], []
for held, targets in NEXT.items():
    for tgt in targets:
        a, na = pooled(JOINT, tgt)
        b, nb = pooled(f'greedy+10x25+family+spec-{held}', tgt)
        if a is None or b is None:
            missing.append(f'spec-{held} on {tgt} ({na} vs {nb} seeds)')
            continue
        if na != nb:
            asym.append(f'spec-{held} on {tgt}: {na} vs {nb} seeds')
            continue
        m, lo, hi, p = ci(100 * (a - b) / b)
        pairs.append(dict(held=held, target=tgt, mean=m, lo=lo, hi=hi, p=p,
                          n=len(a), seeds=na))

if missing:
    refuse(MACROS, 'missing evaluations: ' + '; '.join(missing))
    sys.exit(1)
if asym:
    refuse(MACROS, 'asymmetric seed pools: ' + '; '.join(asym))
    sys.exit(1)

for pr, q in zip(pairs, holm([p['p'] for p in pairs])):
    pr['p_holm'] = q
    pr['joint_ahead'] = bool(pr['hi'] < 0 and q < ALPHA)

ahead = sum(p['joint_ahead'] for p in pairs)
allg = np.concatenate([
    100 * (pooled(JOINT, p['target'])[0]
           - pooled(f'greedy+10x25+family+spec-{p["held"]}', p['target'])[0])
    / pooled(f'greedy+10x25+family+spec-{p["held"]}', p['target'])[0]
    for p in pairs])
m, lo, hi, _ = ci(allg)
worst = min(pairs, key=lambda p: p['mean'])

print(f'{"stale spec":12s} {"on":5s} {"gap":>7s}  {"CI":>16s}  p_holm  ahead')
for p in pairs:
    print(f'spec-{p["held"]:<7s} {p["target"]:5s} {p["mean"]:+7.2f}  '
          f'[{p["lo"]:+6.2f},{p["hi"]:+6.2f}]  {p["p_holm"]:.4f}  '
          f'{"yes" if p["joint_ahead"] else ""}')
print(f'  -> joint ahead on {ahead}/{len(pairs)}; pooled {m:+.2f}% '
      f'[{lo:+.2f},{hi:+.2f}]; worst for the stale specialist: '
      f'spec-{worst["held"]} on {worst["target"]} at {worst["mean"]:+.2f}%')

emit(MACROS, ([
    '% auto-generated by scripts/p54_coverage_lag.py -- do not hand-edit',
    '% joint vs the specialist a plant still has when one rule is added.',
    '% Negative = the joint policy is faster.',
    f'\\newcommand{{\\StaleN}}{{{len(pairs)}}}',
    f'\\newcommand{{\\StaleAhead}}{{{ahead}}}',
    f'\\newcommand{{\\StaleMeanAbs}}{{{abs(m):.2f}}}'
    f'\\newcommand{{\\StaleWorstAbs}}{{{abs(worst["mean"]):.2f}}}'
    f'\\newcommand{{\\StaleMean}}{{{m:+.2f}}}'
    f'\\newcommand{{\\StaleLo}}{{{lo:+.2f}}}'
    f'\\newcommand{{\\StaleHi}}{{{hi:+.2f}}}',
    f'\\newcommand{{\\StaleWorst}}{{{worst["mean"]:+.2f}}}'
    f'\\newcommand{{\\StaleWorstHeld}}{{{worst["held"]}}}'
    f'\\newcommand{{\\StaleWorstTarget}}{{{worst["target"]}}}',
]))

os.makedirs('results', exist_ok=True)
with open(DATA, 'w') as f:
    json.dump(dict(pairs=pairs, pooled=dict(mean=m, lo=lo, hi=hi),
                   alpha=ALPHA), f, indent=1)
print(f'wrote {DATA}')
