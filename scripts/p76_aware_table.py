r"""Supplement tables of the constraint-aware dispatching rules.

Reads results/aware_rules.json (written by scripts/p72_aware_rules.py) and
writes two booktabs tabulars, one block per size:
  paper/tables/aware_table.tex       10, 20 and 30 modules (all test instances)
  paper/tables/aware_table_prod.tex  50 and 80 modules (first 10 per regime)
Rows are the eight regimes plus a pooled row. Columns are the mean makespan
(h) of SPT and of the PACT policy, then for ECT, SSPT and LLF the mean
makespan and the gap to SPT with its 95% paired-bootstrap CI, exactly as p72
computed them (gap = mean over instances of 100*(rule - SPT)/SPT, positive =
rule worse). The pooled means are the instance-weighted means of the regime
means. Bold marks the lowest mean makespan in each row across all five
methods, compared at printed precision so that ties are all bolded.

It also writes paper/macros_awaretab.tex with the magnitudes of the pooled
SSPT-to-SPT gaps at 10 and 80 modules, for prose that says "improves by".
Before writing, the pooled gaps are asserted, at printed precision, against
paper/macros_aware.tex; on a mismatch nothing is written.

Usage (from the repository root):
  taskset -c 14 python scripts/p76_aware_table.py
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'results', 'aware_rules.json')
OUT_MAIN = os.path.join(ROOT, 'paper', 'tables', 'aware_table.tex')
OUT_PROD = os.path.join(ROOT, 'paper', 'tables', 'aware_table_prod.tex')
OUT_MAC = os.path.join(ROOT, 'paper', 'macros_awaretab.tex')
MAC_AWARE = os.path.join(ROOT, 'paper', 'macros_aware.tex')

REGIMES = ['N', 'L', 'S', 'W', 'LS', 'LW', 'SW', 'LSW']
RULES = ['ECT', 'SSPT', 'LLF']
METHODS = ['SPT', 'PACT'] + RULES
HEADER = '% auto-generated by scripts/p76_aware_table.py -- do not hand-edit\n'


def signed(x):
    s = f'{x:.2f}'
    if s in ('0.00', '-0.00'):
        return '0.00'
    return ('$-$' + s[1:]) if s.startswith('-') else ('$+$' + s)


def gap_cell(g):
    return f'{signed(g[0])} [{signed(g[1])}, {signed(g[2])}]'


def row_cells(means, gaps):
    shown = {m: f'{means[m]:.1f}' for m in METHODS}
    best = min(float(v) for v in shown.values())
    fmt = {m: (r'\textbf{' + v + '}' if float(v) == best else v)
           for m, v in shown.items()}
    cells = [fmt['SPT'], fmt['PACT']]
    for r in RULES:
        cells += [fmt[r], gap_cell(gaps[r])]
    return cells


def block(size, S):
    n = S['regimes'][REGIMES[0]]['n']
    modules = int(size.split('x')[0])
    lines = [r'\multicolumn{9}{@{}l}{\textit{' + f'{modules} modules, '
             f'$n = {n}$ instances per regime' + r'}} \\']
    tot = {m: 0.0 for m in METHODS}
    ntot = 0
    for g in REGIMES:
        R = S['regimes'][g]
        means = {m: R[f'mean_{m}'] for m in METHODS}
        gaps = {r: R[f'gap_SPT_{r}'] for r in RULES}
        for m in METHODS:
            tot[m] += R['n'] * means[m]
        ntot += R['n']
        lines.append(f'${g}$ & ' + ' & '.join(row_cells(means, gaps)) + r' \\')
    P = S['pooled']
    for r in RULES:
        assert P[r]['n'] == ntot, (size, r, P[r]['n'], ntot)
    means = {m: tot[m] / ntot for m in METHODS}
    gaps = {r: P[r]['gap_SPT'] for r in RULES}
    lines.append('pooled & ' + ' & '.join(row_cells(means, gaps)) + r' \\')
    return lines


def tabular(sizes, D):
    out = [HEADER,
           r'\begin{tabular}{@{}l rr rl rl rl@{}}', r'\toprule',
           r' & & & \multicolumn{2}{c}{ECT} & \multicolumn{2}{c}{SSPT}'
           r' & \multicolumn{2}{c}{LLF} \\',
           r'\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(l){8-9}',
           r'Regime & SPT & PACT & mean & gap to SPT [95\% CI]'
           r' & mean & gap to SPT [95\% CI] & mean & gap to SPT [95\% CI] \\']
    for i, size in enumerate(sizes):
        out.append(r'\midrule')
        out += block(size, D['sizes'][size])
    out += [r'\bottomrule', r'\end{tabular}', '']
    return '\n'.join(out)


def macro_value(text, name):
    m = re.search(r'\\newcommand\{\\' + name + r'\}\{([^}]*)\}', text)
    if not m:
        sys.exit(f'macro {name} missing from {MAC_AWARE}')
    return m.group(1)


def main():
    D = json.load(open(SRC))
    if D.get('identity_failures'):
        sys.exit(f'identity failures recorded in {SRC}: {D["identity_failures"]}')
    for size in ['10x25', '20x25', '30x25', '50x25', '80x25']:
        assert size in D['sizes'], size

    mac = open(MAC_AWARE).read()
    abs_macros = []
    for size, w in [('10x25', 'Ten'), ('80x25', 'Eighty')]:
        S = D['sizes'][size]
        b = S['best_rule']
        assert b == macro_value(mac, f'AwareBest{w}'), (size, b)
        gs = S['pooled'][b]['gap_SPT']
        gp = S['pooled'][b]['gap_PACT']
        for key, val in [(f'AwareGapSpt{w}', gs[0]), (f'AwareGapSpt{w}Lo', gs[1]),
                         (f'AwareGapSpt{w}Hi', gs[2]), (f'AwareGapPact{w}', gp[0]),
                         (f'AwareGapPact{w}Lo', gp[1]), (f'AwareGapPact{w}Hi', gp[2])]:
            assert f'{val:.1f}' == macro_value(mac, key), (key, val)
        abs_macros.append((f'AwareGapSpt{w}Abs', f'{abs(gs[0]):.1f}',
                           f'{size}: magnitude of the pooled gap of {b} to SPT, %'))

    with open(OUT_MAIN, 'w') as f:
        f.write(tabular(['10x25', '20x25', '30x25'], D))
    with open(OUT_PROD, 'w') as f:
        f.write(tabular(['50x25', '80x25'], D))
    with open(OUT_MAC, 'w') as f:
        f.write(HEADER)
        for k, v, c in abs_macros:
            f.write(f'\\newcommand{{\\{k}}}{{{v}}}  % {c}\n')
    for p in (OUT_MAIN, OUT_PROD, OUT_MAC):
        print('wrote', os.path.relpath(p, ROOT))


if __name__ == '__main__':
    main()
